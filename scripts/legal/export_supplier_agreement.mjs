// Exports the Supplier Agreement from src/content/legal.json into a module supplier_api can read, so
// accept_terms records a SHA-256 of the exact text accepted (website audit SPF5, 14 Sep 2026).
//
//   node scripts/legal/export_supplier_agreement.mjs v8
//
// The version argument is the value app_secrets('terms_version') holds for this text. supplier_api
// stores the hash only while that secret still names this version, so editing the agreement means:
// change legal.json, bump the secret, re-run this with the new version, deploy supplier_api.
// --check exits 1 when either module no longer matches legal.json (for CI or a pre-commit look).
//
// TWO MODULES (16 Nov 2026, it_engineer, DUP item 1). supplier_agreement.ts carries the text (87,725 bytes) for the
// scripts and checks that read it; supplier_agreement_hash.ts carries only the version and the SHA-256, which is all
// an edge function stores (_shared/supplier_terms.ts). The text no longer rides in supplier_api, customer_api and kyc.
//
// A COPY PASS OVER legal.json MUST SKIP THE THREE AGREEMENT DOCUMENTS. 22 Sep 2026: the website
// audit's Arabic corrections (WEB-06/07 — the supplier's name with its shadda, the legal-centre
// title) were applied file-wide and reached `supplier-agreement`, `-v11` and `-v10`. Those are the
// words suppliers signed: the body is hashed here, stored against each acceptance, and asserted word
// for word by supplier_agreement_v11_is_published_and_reaccepted and
// supplier_agreement_v12_notices_go_to_the_confirmed_whatsapp, which is exactly what caught it. The
// three documents were restored byte for byte. Their wording changes only as a NEW version: edit,
// bump `terms_version`, re-export, deploy supplier_api, and every supplier is asked to accept again.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const args = process.argv.slice(2);
const OUT = new URL('../../supabase/functions/_shared/supplier_agreement.ts', import.meta.url);
const OUT_HASH = new URL('../../supabase/functions/_shared/supplier_agreement_hash.ts', import.meta.url);
const legal = JSON.parse(readFileSync(new URL('../../src/content/legal.json', import.meta.url), 'utf8'));
const sa = legal['supplier-agreement'];
if (!sa?.en?.html || !sa?.ar?.html) { console.error('supplier-agreement en/ar html missing from legal.json'); process.exit(1); }
const sha = createHash('sha256').update(sa.en.html + '\n' + sa.ar.html, 'utf8').digest('hex');

if (args.includes('--check')) {
  let stale = 0;
  for (const f of [OUT, OUT_HASH]) {
    const name = f.pathname.split('/').pop();
    const cur = readFileSync(f, 'utf8').match(/SHA256 = '([0-9a-f]{64})'/)?.[1];
    console.log(cur === sha ? `${name} matches legal.json` : `STALE: ${name} ${cur} vs legal.json ${sha}`);
    if (cur !== sha) stale++;
  }
  const v = (f) => readFileSync(f, 'utf8').match(/SUPPLIER_AGREEMENT_VERSION = ("[^"]*")/)?.[1];
  if (v(OUT) !== v(OUT_HASH)) { console.log(`STALE: version ${v(OUT)} in supplier_agreement.ts, ${v(OUT_HASH)} in supplier_agreement_hash.ts`); stale++; }
  process.exit(stale ? 1 : 0);
}
const version = args.find((a) => !a.startsWith('--'));
if (!version || !/^[\w.-]{1,20}$/.test(version)) { console.error('usage: export_supplier_agreement.mjs <version> | --check'); process.exit(1); }

writeFileSync(OUT, `// GENERATED by scripts/legal/export_supplier_agreement.mjs from src/content/legal.json — do not edit.
// The exact Supplier Agreement text a supplier accepts, and its SHA-256 (EN html + '\\n' + AR html,
// UTF-8). supplier_api writes the hash to leads.accepted_terms_sha256 at accept_terms.
export const SUPPLIER_AGREEMENT_VERSION = ${JSON.stringify(version)};
export const SUPPLIER_AGREEMENT_SHA256 = '${sha}';
export const SUPPLIER_AGREEMENT_EN = ${JSON.stringify(sa.en.html)};
export const SUPPLIER_AGREEMENT_AR = ${JSON.stringify(sa.ar.html)};
`);
writeFileSync(OUT_HASH, `// GENERATED by scripts/legal/export_supplier_agreement.mjs from src/content/legal.json — do not edit.
// The Supplier Agreement's version and the SHA-256 of its text (EN html + '\\n' + AR html, UTF-8), without the text
// (supplier_agreement.ts). supplier_api, customer_api and kyc store this hash at accept_terms (_shared/supplier_terms.ts).
export const SUPPLIER_AGREEMENT_VERSION = ${JSON.stringify(version)};
export const SUPPLIER_AGREEMENT_SHA256 = '${sha}';
`);
console.log(`wrote supplier_agreement.ts and supplier_agreement_hash.ts version=${version} sha256=${sha}`);
