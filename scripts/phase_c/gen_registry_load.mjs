// Generate scripts/sql/phase_c_05_registry_load.sql from the committed package and the
// measured deliverable CSVs.
//
//   node scripts/phase_c/gen_registry_load.mjs
//
// The migration is GENERATED rather than hand-written because it carries ~2,500 rows that must
// agree exactly with the CSVs the founder is shown.  Generating both from one source is what
// makes "the CSV says X and the database says X" a fact rather than a hope.
//
// The command-routing rules at the end are the deterministic registry the master spec asks for.
// They are DATA: `select * from phase_c_command_rule order by rule_order` shows exactly how any
// sentence will be routed, without reading a function body.  No model is involved anywhere.
