// ------------------------------------------------------------------ the bindings
// One file per binding registry, for the same reason the components are split: the management
// API applies a file as one POST.
const bindingFiles = [];
let bindingSeq = 0;
const loadBinding = (csvName, table, pk, cols) => {
  const rows = readCSV(join(OUT, csvName));
  const B = [`-- Phase C — ${table} (${rows.length} rows from ${csvName}).
-- GENERATED by scripts/phase_c/gen_registry_load.mjs; do not edit by hand.

set lock_timeout = '8s';
set statement_timeout = '600s';
`];
  for (const part of chunk(rows, 150)) {
    B.push(`insert into public.${table} (${cols.map(c => c[0]).join(', ')}) values`);
    B.push(part.map(r => `  (${cols.map(c => q(typeof c[1] === 'function' ? c[1](r) : r[c[1]])).join(', ')})`).join(',\n'));
    B.push(`on conflict (${pk}) do update set ${cols.filter(c => c[0] !== pk).map(c => `${c[0]} = excluded.${c[0]}`).join(', ')};`);
  }
  bindingSeq += 1;
  const name = `phase_c_07_binding_${String(bindingSeq).padStart(2, '0')}_${table.replace(/^phase_c_/, '')}.sql`;
  const text = B.join('\n') + '\n';
  writeFileSync(join(REPO, 'scripts', 'sql', name), text, 'utf8');
  bindingFiles.push([name, Math.round(text.length / 1024), rows.length]);
  return rows.length;
};

