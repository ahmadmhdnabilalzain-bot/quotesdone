// Generate scripts/sql/surfaces_carry_alternatives.sql — the four action surfaces projecting
// decision_log.alternatives.
//
// WHY GENERATED RATHER THAN HAND-WRITTEN. These four routines are 1.7k-3.2k characters of dense
// jsonb_build_object, and the change to each is a single added key. Retyping them by hand to add one
// key is how a body drifts: the promotion rule exists precisely because a retyped body is not the
// verified body. So the definition is read back from the live database, one exact string is replaced,
// and the result is what gets applied.
//
//   node scripts/gen_surfaces_carry_alternatives.mjs
//   node scripts/apply_sql.mjs scripts/sql/surfaces_carry_alternatives.sql --promote
//
// THE JOIN. Only fn_os_command reads decision_log directly; the other three read agent_actions and
// reach the ledger row through agent_actions.decision_log_id. That column dates from 6 Aug, so it is
// null on two thirds of the currently surfaced approvals and those rows get a null alternatives.
// That is deliberate — see gate_records_the_alternative_it_rejected.sql. No value is synthesised for
// a decision that recorded no evaluation.
import { writeFileSync } from 'node:fs';
import { mgmtRead, PROD_REF } from './staging/qd_guard.mjs';

// Reaches decision_log.alternatives from the agent_actions row currently in scope.
//
// UNQUALIFIED decision_log_id ON PURPOSE. The three agent_actions surfaces do not agree on how the
// row is in scope: fn_ws_governance selects `from public.agent_actions` directly, while
// fn_ws_operations and fn_ea_agenda both wrap it in a derived table (`from (select * from
// agent_actions ...) a`). Qualifying it as `agent_actions.decision_log_id` therefore fails on the two
// derived-table forms with "missing FROM-clause entry" — measured, on the first apply. The column is
// carried by the `select *` in every case and is the only candidate in scope, so the bare name
// resolves in all three.
const VIA = () =>
  `(select d.alternatives from public.decision_log d where d.id = decision_log_id)`;

const EDITS = [
  {
    fn: 'fn_os_command',
    // reads decision_log directly, so the column is in scope on the row itself
    find: `'reasons', reasons,`,
    repl: `'reasons', reasons,\n             'alternatives', alternatives,`,
  },
  {
    fn: 'fn_ws_governance',
    find: `public.fn_owning_os(agent) as os,`,
    repl: `public.fn_owning_os(agent) as os,\n               ${VIA()} as alternatives,`,
  },
  {
    fn: 'fn_ws_operations',
    find: `'os', public.fn_owning_os(agent), 'confidence', confidence,`,
    repl: `'os', public.fn_owning_os(agent), 'confidence', confidence,\n        'alternatives', ${VIA()},`,
  },
  {
    fn: 'fn_ea_agenda',
    find: `'os', public.fn_owning_os(agent),`,
    repl: `'os', public.fn_owning_os(agent),\n            'alternatives', ${VIA()},`,
  },
];

const out = [
  `-- GENERATED by scripts/gen_surfaces_carry_alternatives.mjs — do not hand-edit.`,
  `--`,
  `-- The four action surfaces named by the Layer 15 scorer now project decision_log.alternatives:`,
  `--   escalations  fn_os_command().attention              (reads decision_log directly)`,
  `--   governance   fn_ws_governance().recent_escalations   (agent_actions -> decision_log_id)`,
  `--   operations   fn_ws_operations().approvals            (agent_actions -> decision_log_id)`,
  `--   assistant    fn_ws_ea().approvals_top                (comes from fn_ea_agenda, edited here)`,
  `--`,
  `-- Each body was read back from production and had exactly one key added. Rows whose action`,
  `-- predates agent_actions.decision_log_id (6 Aug) carry null, on purpose: they recorded no`,
  `-- evaluation and one must not be invented for them.`,
  ``,
];

let failed = 0;
for (const e of EDITS) {
  const rows = await mgmtRead(
    PROD_REF,
    `select pg_get_functiondef(p.oid) as def from pg_proc p join pg_namespace n on n.oid=p.pronamespace
      where n.nspname='public' and p.proname=${JSON.stringify(e.fn).replace(/"/g, "'")}`,
  );
  const def = rows?.[0]?.def;
  if (!def) { console.error(`MISSING ${e.fn}`); failed++; continue; }
  const hits = def.split(e.find).length - 1;
  if (hits !== 1) {
    console.error(`ANCHOR ${e.fn}: found ${hits} occurrence(s) of the anchor, expected exactly 1 — refusing`);
    failed++; continue;
  }
  if (/'alternatives'/.test(def)) { console.log(`SKIP ${e.fn} already projects alternatives`); continue; }
  out.push(def.replace(e.find, e.repl).trimEnd() + ';', '');
  console.log(`OK   ${e.fn} (+1 key)`);
}

if (failed) { console.error(`\n${failed} function(s) could not be rewritten; nothing written`); process.exit(1); }
writeFileSync('scripts/sql/surfaces_carry_alternatives.sql', out.join('\n'));
console.log('\nwrote scripts/sql/surfaces_carry_alternatives.sql');
