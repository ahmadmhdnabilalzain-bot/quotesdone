// Generate scripts/sql/what_if_measures_the_cache.sql — fn_what_if stops telling the founder a
// hardcoded cache figure and measures it.
//
// MEASURED, production 11 Aug 2026. Asked "What happens if the OpenRouter AI cost doubles?",
// fn_what_if answered with, among real computed numbers:
//
//   "Model policy already routes by task class; cache adoption is 0%, so caching is the first lever."
//
// The 0% is a STRING LITERAL. It was true when it was written — cachedIn read two field names
// OpenRouter does not return, so the meter said zero on every call the company had ever made — and
// the gateway's cache accounting was fixed earlier today. The literal was not. It will read 0%
// forever, whatever the cache does, sitting inside a projection whose other three figures are
// genuinely computed.
//
// That is the exact thing the OS_PORTALS gate "No mock metrics or invented market values are shown
// as facts" exists to prevent, in a routine the founder reads to make a spend decision.
//
// The replacement measures ai_cost_log's real columns — cached_in_tokens against prompt_tokens, the
// nested prompt_tokens_details fields the gateway now records — and prints the write volume beside
// the read so the number cannot be read as free. Over the 30 days to 11 Aug that is 9,851 read
// against 12,114,321 prompt tokens: 0.1%, which is honestly near zero because caching only began
// working today, and which will move on its own as the loop runs.
//
//   node scripts/archive/gen_what_if_measures_the_cache.mjs
//   node scripts/apply_sql.mjs scripts/sql/what_if_measures_the_cache.sql --promote
import { writeFileSync } from 'node:fs';
import { mgmtRead, PROD_REF } from '../lib/qd_guard.mjs';

const ANCHOR =
  `'mitigation','Model policy already routes by task class; cache adoption is 0%, so caching is the first lever.'`;

const REPL = `'mitigation','Model policy already routes by task class. Prompt-cache reads are '
        ||coalesce((select round(100.0*sum(cached_in_tokens)/nullif(sum(prompt_tokens),0),1)::text
                      from ai_cost_log where occurred_at > now() - interval '30 days'),'0')
        ||'% of prompt tokens over 30 days ('
        ||coalesce((select sum(cached_in_tokens)::text from ai_cost_log
                     where occurred_at > now() - interval '30 days'),'0')
        ||' read against '
        ||coalesce((select sum(cache_write_tokens)::text from ai_cost_log
                     where occurred_at > now() - interval '30 days'),'0')
        ||' written at a 1.25x premium), so caching pays only above roughly 22% and is measured here rather than assumed.'`;

const rows = await mgmtRead(
  PROD_REF,
  `select pg_get_functiondef(p.oid) as def from pg_proc p join pg_namespace n on n.oid=p.pronamespace
    where n.nspname='public' and p.proname='fn_what_if'`,
);
const def = rows?.[0]?.def;
if (!def) { console.error('fn_what_if not found'); process.exit(1); }
if (/Prompt-cache reads are/.test(def)) { console.log('SKIP already measured'); process.exit(0); }
const hits = def.split(ANCHOR).length - 1;
if (hits !== 1) { console.error(`ANCHOR found ${hits} time(s), expected exactly 1 — refusing`); process.exit(1); }

writeFileSync(
  'scripts/sql/what_if_measures_the_cache.sql',
  [
    `-- GENERATED by scripts/gen_what_if_measures_the_cache.mjs — do not hand-edit.`,
    `--`,
    `-- "cache adoption is 0%" was a string literal in a projection whose other figures are computed.`,
    `-- It was true when the cache meter was broken and stayed true after the meter was fixed. It now`,
    `-- reads ai_cost_log.cached_in_tokens against prompt_tokens, and prints the write volume beside`,
    `-- the read so the figure cannot be mistaken for a free saving.`,
    ``,
    def.replace(ANCHOR, REPL).trimEnd() + ';',
    ``,
  ].join('\n'),
);
console.log('OK   fn_what_if mitigation line now measured\nwrote scripts/sql/what_if_measures_the_cache.sql');
