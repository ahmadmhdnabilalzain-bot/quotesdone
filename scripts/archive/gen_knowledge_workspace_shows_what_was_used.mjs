// Generate scripts/sql/knowledge_workspace_shows_what_was_used.sql — kb_usage_log gets a reader.
//
// MEASURED, production 11 Aug 2026: kb_usage_log holds 78 rows, all written in the last 7 days, by
// 11 distinct agents. Nothing reads it. Not one database routine so much as mentions the table:
//
//   select string_agg(p.proname,', ') from pg_proc p ... where pg_get_functiondef(p.oid) ~* 'kb_usage_log'
//   -> null
//
// agent_brain writes it on every knowledge retrieval and the record has never been looked at. That
// is the same defect the audit keeps finding — graph_nodes with 336 nodes and zero readers,
// model_policy_by_identity with 120 rows and zero readers, agent_expectations with 36 rows and zero
// readers. Written, never read.
//
// The knowledge workspace is where it belongs and is already reachable: os_api maps ws.knowledge ->
// fn_ws_knowledge as read_only, so this needs no new action, no new route and no permission change.
//
// WHAT IT DOES NOT DO. It does not close employee-knowledge-used. That check also requires every
// employee who decided anything in 7 days to have a usage record, and 22 of the 32 deciders are
// deterministic monitors — supplier_risk_monitor alone wrote 78 gated actions — that never consult
// the knowledge base at all. Their retrieval is real but it is a policy and authority lookup, and it
// is already recorded in decision_log.sources by the gate. Routing them through the KB to satisfy a
// counter, or writing usage rows they did not earn, would both be inventing a retrieval. So the
// check stays MISSING and this simply makes 78 real records visible.
//
//   node scripts/archive/gen_knowledge_workspace_shows_what_was_used.mjs
//   node scripts/apply_sql.mjs scripts/sql/knowledge_workspace_shows_what_was_used.sql --promote
import { writeFileSync } from 'node:fs';
import { mgmtRead, PROD_REF } from '../lib/qd_guard.mjs';

const ANCHOR = `    'recent', coalesce((select jsonb_agg(`;

const BLOCK = `    -- WHICH KNOWLEDGE WAS ACTUALLY USED, and by whom. agent_brain writes a row here on every
    -- retrieval; until now nothing read them back, so "the knowledge is being used" was an
    -- assertion rather than something the founder could check.
    'used', coalesce((select jsonb_agg(jsonb_build_object(
        'agent', u.agent, 'query', left(coalesce(u.query,''), 90),
        'category', u.category, 'at', u.created_at) order by u.created_at desc)
      from (select * from kb_usage_log order by created_at desc limit 25) u),'[]'::jsonb),
    'used_kpis', jsonb_build_object(
      'lookups_7d', (select count(*) from kb_usage_log where created_at > now() - interval '7 days'),
      'agents_7d', (select count(distinct agent) from kb_usage_log where created_at > now() - interval '7 days'),
      'categories_7d', (select count(distinct category) from kb_usage_log
                         where created_at > now() - interval '7 days' and category is not null)
    ),
` + ANCHOR;

const rows = await mgmtRead(
  PROD_REF,
  `select pg_get_functiondef(p.oid) as def from pg_proc p join pg_namespace n on n.oid=p.pronamespace
    where n.nspname='public' and p.proname='fn_ws_knowledge'`,
);
const def = rows?.[0]?.def;
if (!def) { console.error('fn_ws_knowledge not found'); process.exit(1); }
if (/kb_usage_log/.test(def)) { console.log('SKIP already reads kb_usage_log'); process.exit(0); }
const hits = def.split(ANCHOR).length - 1;
if (hits !== 1) { console.error(`ANCHOR found ${hits} time(s), expected exactly 1 — refusing`); process.exit(1); }

writeFileSync(
  'scripts/sql/knowledge_workspace_shows_what_was_used.sql',
  [
    `-- GENERATED by scripts/gen_knowledge_workspace_shows_what_was_used.mjs — do not hand-edit.`,
    `--`,
    `-- kb_usage_log held 78 rows from 11 agents and had ZERO readers — not one database routine even`,
    `-- named the table. The knowledge workspace now shows which knowledge was looked up and by whom.`,
    `-- ws.knowledge -> fn_ws_knowledge is already mapped read_only in os_api, so no new action, no`,
    `-- new route and no permission change.`,
    ``,
    def.replace(ANCHOR, BLOCK).trimEnd() + ';',
    ``,
  ].join('\n'),
);
console.log('OK   fn_ws_knowledge now reads kb_usage_log\nwrote scripts/sql/knowledge_workspace_shows_what_was_used.sql');
