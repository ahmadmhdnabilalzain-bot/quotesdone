// A PREFERENCE PROFILE IS PERSONAL DATA, AND THE ERASURE PATH DID NOT KNOW THE TABLE EXISTED.
//
// fn_pdpl_redact resolves the subject then redacts thirteen tables; fn_pdpl_export enumerates what
// a subject may request. Neither mentions customer_preference — which was harmless while the table
// held 0 rows and stopped being harmless the moment it got a writer. Adding the writer without
// this is how a company ends up unable to honour an erasure request it has already promised.
//
// DELETE, not redact. There is nothing in a preference profile worth keeping once the subject is
// gone, and an emptied row would still assert "this person consented", which after erasure is
// false. Withdrawal of consent is the same delete: row absent is indistinguishable from never
// consented, by design, so no tombstone is needed and none is written.
//
// Generated by exact-match replacement against the LIVE definitions for the same reasons as
// gen_customer_360_reader.mjs: fn_pdpl_redact is 6,798 characters, the checked-in schema dump is
// stale, and a rewrite that reports success without running is the documented failure mode here.
//
//   node scripts/archive/gen_pdpl_customer_preference.mjs
import { writeFileSync } from 'node:fs';
import { mgmtRead, PROD_REF } from '../lib/qd_guard.mjs';

const rows = await mgmtRead(PROD_REF,
  `select p.proname n, pg_get_functiondef(p.oid) d from pg_proc p
     join pg_namespace ns on ns.oid = p.pronamespace
    where ns.nspname='public' and p.proname in ('fn_pdpl_redact','fn_pdpl_export')`);
const live = Object.fromEntries(rows.map(r => [r.n, r.d]));

const EDITS = [
  { fn: 'fn_pdpl_redact',
    // Placed immediately after subject linkage is resolved and BEFORE any identity field is
    // mutated — the same ordering the function's own comment insists on, because once
    // customers.email is redacted the subject can no longer be found.
    anchor: `  select coalesce(array_agg(id),'{}') into v_inq_ids from public.inquiries where customer_id = any(v_cust_ids);`,
    replacement: `  select coalesce(array_agg(id),'{}') into v_inq_ids from public.inquiries where customer_id = any(v_cust_ids);

  -- customer_preference is DELETED, not redacted: a preference profile has nothing to retain, and
  -- an emptied row would still carry consented_at and so still assert a consent that no longer
  -- exists. Withdrawal of consent is this same delete.
  delete from public.customer_preference where customer_id = any(v_cust_ids);` },

  { fn: 'fn_pdpl_export',
    anchor: `    'inquiries',           (select coalesce(jsonb_agg(to_jsonb(i)),'[]'::jsonb) from public.inquiries i where i.customer_id in (select id from public.customers where email=p_email)),`,
    replacement: `    'inquiries',           (select coalesce(jsonb_agg(to_jsonb(i)),'[]'::jsonb) from public.inquiries i where i.customer_id in (select id from public.customers where email=p_email)),
    'preferences',         (select coalesce(jsonb_agg(to_jsonb(cp)),'[]'::jsonb) from public.customer_preference cp where cp.customer_id in (select id from public.customers where email=p_email)),` },
];

let out = `-- GENERATED by scripts/gen_pdpl_customer_preference.mjs from the LIVE production definitions.
-- Do not hand-edit: regenerate. Adds public.customer_preference to the PDPL erasure and export
-- paths, which enumerate their tables by name and so could not have picked it up on their own.
`;
for (const e of EDITS) {
  const src = live[e.fn];
  if (!src) { console.error(`REFUSED: ${e.fn} not found on production`); process.exit(1); }
  if (src.includes('customer_preference')) {
    console.log(`${e.fn}: already references customer_preference — skipped, nothing to do`);
    continue;
  }
  const hits = src.split(e.anchor).length - 1;
  if (hits !== 1) {
    console.error(`REFUSED: ${e.fn} anchor matched ${hits} time(s), expected exactly 1.`);
    process.exit(1);
  }
  out += `\n${src.replace(e.anchor, e.replacement)};\n`;
  console.log(`${e.fn}: anchor matched once, edit staged`);
}
writeFileSync('scripts/sql/fn_pdpl_customer_preference.sql', out, 'utf8');
console.log('written scripts/sql/fn_pdpl_customer_preference.sql');
