// Generate scripts/sql/company_map_places_suppliers_and_knowledge.sql — the company map places the
// two things the company actually has.
//
// MEASURED, production 11 Aug 2026. company-map-entities wants six classes on the map and finds
// three:
//
//   graph_nodes kinds: category, department, employee, goal, operating_system, responsibility, workflow
//   departments YES   processes YES (workflow)   employees YES
//   customers NO      suppliers NO               knowledge NO
//
// customers is honestly empty — the marketplace has none. The other two are not:
//
//   leads      20,470 rows
//   kb_chunks 120,530 rows
//
// So the founder's company map shows his org chart and his goals, and omits his supplier book and
// his knowledge base, which are the two largest assets the company owns. That is not a data gap, it
// is a builder that was never asked for them.
//
// SHAPE. 20,470 supplier dots is not a map, it is a hairball. The node is the POOL per category,
// built from v_supply_gap — the company's own supply-gap view, so the map and the supply reports
// cannot disagree — and its label carries sendable/invited/approved so the node says something
// rather than merely existing. Knowledge is one node per KB category with its chunk count.
//
// Edges hang both off the category node that already exists, which is what makes the map walkable:
// department -> category -> supplier pool, and department -> category -> knowledge. The knowledge
// edge is guarded by an exists() against catalog_supplier_categories because kb_chunks.category also
// carries non-category values like 'agent_context', and a dangling edge is worse than no edge.
//
// IT DOES NOT CLOSE THE CHECK. Six classes are required and customers is genuinely zero, so this
// takes company-map-entities from 3 of 6 to 5 of 6 and s22-graph-navigation from 2 of 9 to 4 of 9.
// Both stay MISSING until the marketplace has customers. The map becomes true either way.
//
//   node scripts/gen_company_map_places_suppliers_and_knowledge.mjs
//   node scripts/apply_sql.mjs scripts/sql/company_map_places_suppliers_and_knowledge.sql --promote
import { writeFileSync } from 'node:fs';
import { mgmtRead, PROD_REF } from '../lib/qd_guard.mjs';

const NODE_ANCHOR = `  union all select 'responsibility', responsibility, responsibility from os_responsibility
  on conflict do nothing;`;

const NODE_REPL = `  union all select 'responsibility', responsibility, responsibility from os_responsibility
  -- THE SUPPLY BOOK. One node per category pool rather than 20,470 dots, built from v_supply_gap so
  -- the map and the supply reports read from the same numbers. The label carries the state, so the
  -- node says something.
  union all select 'supplier_pool', g.slug,
         g.name || ' — ' || g.sendable || ' sendable, ' || g.invited || ' invited, ' || g.approved || ' approved'
    from v_supply_gap g
  -- THE KNOWLEDGE BASE. One node per KB category with its depth.
  union all select 'knowledge', k.category, k.category || ' — ' || k.n || ' chunk(s)'
    from (select category, count(*) n from kb_chunks where category is not null group by category) k
  on conflict do nothing;`;

const EDGE_ANCHOR = `,true))
  on conflict do nothing;
  get diagnostics n_edges = row_count;`;

const EDGE_REPL = `,true))
  -- Both hang off the category node that already exists, which is what makes the map walkable:
  -- department -> category -> supplier pool, and department -> category -> knowledge.
  union all
  select 'category', g.slug, 'supplied_by', 'supplier_pool', g.slug from v_supply_gap g
  union all
  select 'category', regexp_replace(k.category,'^cat:',''), 'documented_by', 'knowledge', k.category
    from (select distinct category from kb_chunks where category is not null) k
   where exists (select 1 from catalog_supplier_categories c
                  where c.slug = regexp_replace(k.category,'^cat:',''))
  on conflict do nothing;
  get diagnostics n_edges = row_count;`;

const rows = await mgmtRead(
  PROD_REF,
  `select pg_get_functiondef(p.oid) as def from pg_proc p join pg_namespace n on n.oid=p.pronamespace
    where n.nspname='public' and p.proname='fn_graph_rebuild'`,
);
const def = rows?.[0]?.def;
if (!def) { console.error('fn_graph_rebuild not found'); process.exit(1); }
if (/supplier_pool/.test(def)) { console.log('SKIP already places suppliers'); process.exit(0); }
for (const [a, n] of [[NODE_ANCHOR, 'nodes'], [EDGE_ANCHOR, 'edges']]) {
  const hits = def.split(a).length - 1;
  if (hits !== 1) { console.error(`ANCHOR (${n}) found ${hits} time(s), expected exactly 1 — refusing`); process.exit(1); }
}

writeFileSync(
  'scripts/sql/company_map_places_suppliers_and_knowledge.sql',
  [
    `-- GENERATED by scripts/gen_company_map_places_suppliers_and_knowledge.mjs — do not hand-edit.`,
    `--`,
    `-- The company map showed the org chart and the goals and omitted the supplier book (20,470`,
    `-- leads) and the knowledge base (120,530 chunks) — the two largest assets the company owns.`,
    `-- Not a data gap: a builder that was never asked for them. Pools rather than 20,470 dots, built`,
    `-- from v_supply_gap so the map and the supply reports cannot disagree.`,
    ``,
    def.replace(NODE_ANCHOR, NODE_REPL).replace(EDGE_ANCHOR, EDGE_REPL).trimEnd() + ';',
    ``,
  ].join('\n'),
);
console.log('OK   fn_graph_rebuild now places supplier pools and knowledge\nwrote scripts/sql/company_map_places_suppliers_and_knowledge.sql');
