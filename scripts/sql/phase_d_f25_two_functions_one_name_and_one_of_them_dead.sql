-- F25 - two functions, one name, and one of them dead
--
-- F01 added public.fn_phase_d_fixture_context() -- the verifier every Phase D fixture path calls to
-- decide whether a protected context is active. There was already a
-- public.fn_phase_d_fixture_context(p_step_run_id bigint, p_label text): the D-series routine that
-- BUILT a per-step fixture context for the old driver. The 2026-08-21 acceptance recorded that the
-- driver no longer calls it -- "fn_phase_d_fixture_context is gone from the driver" -- and the
-- canonical routine manifest reported the consequence:
--
--     fn_phase_d_fixture_context  DRIFTED — 1 deployed body not in the canonical file
--                                 (2 live overloads, 1 canonical)
--
-- Measured before dropping, over every routine body in public: **0** callers of the two-argument
-- form. It is dead, and worse than dead -- a reader who greps for the name now finds two routines
-- with opposite meanings, one of which MAKES a fixture context and one of which VERIFIES one. That
-- is the shape this estate names "a finished capability with no entry point", with a naming
-- collision on top.
--
-- DROP, not rename. A rename would leave a second name for a thing nobody calls.

DROP FUNCTION IF EXISTS public.fn_phase_d_fixture_context(bigint, text);
