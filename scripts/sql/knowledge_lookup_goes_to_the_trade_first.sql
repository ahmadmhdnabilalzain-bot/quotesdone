-- KNOWLEDGE LOOKUP GOES STRAIGHT TO THE RIGHT AREA FIRST. Seats: sales_engineer (the rule), it_engineer (the routine).
-- Founder's rule, 28 Sep 2026: a seat looking something up goes to the right area before it ranks anything.
--
-- WHAT CHANGES, in both retrieval routines a seat reads at decision time:
--   public.fn_reason_retrieve     (gte-small: the seat exams, email_triage, think() when the read space is gte)
--   public.fn_reason_retrieve_ml  (the fused search: think() reads it while fn_ml_read_space() = 'ml', which is what
--                                  production answered on 28 Sep 2026, so changing only the first routine would have
--                                  left every live think() call ranking as before)
-- Each gains three trailing parameters, all default NULL: p_trade, p_kind, p_area.
--   1. RESOLVE, exact or none, no word ever read.
--      trade  p_trade through public.fn_norm_trades, the estate's exact resolver (a live taxonomy code or an intake
--             slug resolves to its code(s); free text resolves to NULL).
--      kind   the topic inside that trade: p_kind counts only when an entry of the resolved trade carries exactly
--             'kind:<p_kind>' (the tag verified_packs.mjs writes on every entry, #1040).
--      area   the seat's own area: p_area counts only when a row of the seat's own table carries exactly
--             'area:<p_area>' (#1041's loader tag). The seat's area list IS those tags; nothing else resolves.
--   2. FILTER BEFORE RANKING. A resolved trade keeps, of sales_knowledge, that trade's rows (narrowed to the kind when
--      one resolved) plus every row with no trade tag (the seat's general entries); another trade's rows are never
--      candidates. A resolved area keeps, of the seat's own table, that area's rows plus every row with no area tag.
--   3. NOTHING RESOLVED: exactly the ranking before. Sources that carry neither tag are never filtered, and the result
--      shape is unchanged.
--
-- WHY THE AREA IS NOT GUESSED FROM THE QUESTION'S VECTOR. Measured 28 Sep 2026 on the five seat packs of #1041-#1046
-- (English exam questions, gte-small, the area most common among the seat's N nearest own rows when at least M agree):
-- the vote picked an area that holds NO expected entry for 15 of 42 resolved customer_support items (N5/M3), 15 of 35
-- accountant, 22 of 48 it_engineer, 5 of 32 ceo, 1 of 3 marketing; the strictest rule tried (N5/M4) was still wrong on
-- 4 of 18, 5 of 13, 4 of 16, 1 of 13 and 1 of 1. Filtering on that guess would remove the right answer that often, and
-- when the guess is right the nearest rows are already in the area. So an area is resolved only from a caller that
-- knows it, the same exact-or-none rule as the trade.
--
-- CALLERS. think() passes ctx.trade (the value it already gives fn_case_recall) and ctx.area when set; email_triage,
-- the daily recall exam and the seat exams know neither and pass none. The signatures change, so the old ones are
-- dropped; a call with the old argument list resolves to the new routine through the defaults. CREATE grants EXECUTE
-- to PUBLIC, so both are revoked below. APPLY THIS BEFORE the think.ts change deploys: an RPC naming p_trade against
-- the old signature is refused.
--
