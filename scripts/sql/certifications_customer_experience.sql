do $$
declare short_banks text;
begin
  select string_agg(c.name || '=' || coalesce(q.n, 0), ', ' order by c.name)
    into short_banks
    from (values
      ('CCXP (Certified Customer Experience Professional)'),
      ('CCSM (Certified Customer Success Manager)'),
      ('HDI-CSR (HDI Customer Service Representative)'),
      ('HDI-SCA (HDI Support Center Analyst)'),
      ('ITIL 4 Foundation'),
      ('Braze Certified Marketer')
    ) as c(name)
    left join (
      select certification, count(*) as n
        from public.certification_exam_question
       group by certification
    ) q on q.certification = c.name
   where coalesce(q.n, 0) < 40;

  if short_banks is not null then
    raise exception 'certification bank short of 40 questions: %', short_banks;
  end if;
end $$;
