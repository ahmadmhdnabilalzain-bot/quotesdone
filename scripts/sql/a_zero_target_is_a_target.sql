-- A ZERO TARGET IS A TARGET, AND TWO SCORERS DISAGREED WITH THAT.
--
-- Found while correcting a KPI I had written an hour earlier. fn_kpi_scoreboard computes:
--
--     if v is null or t is null or t = 0 then attainment := null;
--
-- so any KPI whose target is ZERO fell into the null branch and the verdict below reported
-- 'NO TARGET'. Measured on production: 7 active employee KPIs have target 0 and 4 of them are
-- measured, and all four came back NO TARGET while carrying a perfectly good target of zero:
--
--   Notifications older than 24h still unsent
--   Category list matches the specification
--   Reveal invoices without a payment record
--   Suppliers gone quiet
--
-- Those four are exactly the KPIs about DEFECTS. "Zero defects" is the commonest shape a quality
-- target takes, and the company could not score a single one of them.
--
-- fn_employee_scorecard - which I wrote earlier tonight and which puts the number in front of the
-- employee - had the same bug from the same cause: it emitted nothing at all when target_value was
-- 0, so the employee saw a KPI with no number beside it. Both are fixed here from one idea:
-- at a zero target, actual <= 0 is 100% and anything above it is 0%.
--
-- Generated by string replacement against the LIVE definitions rather than retyped.

CREATE OR REPLACE FUNCTION public.fn_kpi_scoreboard()
 RETURNS TABLE(kpi_id bigint, agent_key text, department text, kpi text, metric text, cadence text, serves_goal text, target numeric, unit text, actual numeric, attainment numeric, verdict text)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare r record; v numeric; t numeric;
begin
  for r in
    select k.id, k.agent_key, a.department, k.kpi, k.metric, k.cadence,
           k.serves_goal, k.target_value, k.unit, k.measure_sql
    from employee_kpi k
    left join org_agents a on a.agent_key = k.agent_key
    where k.active
    order by a.department nulls last, k.agent_key, k.id
  loop
    v := null;
    begin
      if r.measure_sql is not null then execute r.measure_sql into v; end if;
    exception when others then v := null;
    end;

    t := null;
    begin
      t := r.target_value::numeric;
    exception when others then t := null;
    end;

    kpi_id := r.id; agent_key := r.agent_key; department := r.department;
    kpi := r.kpi; metric := r.metric; cadence := r.cadence;
    serves_goal := r.serves_goal; target := t; unit := r.unit; actual := v;

    if v is null or t is null then
      attainment := null;
    elsif t = 0 then
      -- A ZERO TARGET IS A TARGET (11 Aug 2026). "Zero defects" is the commonest shape a quality
      -- KPI takes - reveal invoices with no payment record, suppliers gone quiet, categories off
      -- the specification, notifications still unsent - and t = 0 short-circuited into
      -- attainment null, which the verdict below then reported as 'NO TARGET'. Four active,
      -- measured KPIs were being told they had no target when zero IS the target, and the four
      -- were exactly the ones about defects.
      attainment := case when v <= 0 then 100.0 else 0.0 end;
    elsif r.unit = 'percent_max' then
      attainment := round(least(100.0, 100.0 * t / nullif(v,0)), 1);
    else
      attainment := round(100.0 * v / t, 1);
    end if;

    verdict := case
      when v is null then 'NO DATA'
      when attainment is null then 'NO TARGET'
      when attainment >= 100 then 'MET'
      when attainment >= 90 then 'NEAR'
      else 'MISSED' end;

    return next;
  end loop;
end
$function$;

CREATE OR REPLACE FUNCTION public.fn_employee_scorecard(p_agent_key text, p_max_chars integer DEFAULT 1400)
 RETURNS text
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare
  v_cap  int := greatest(coalesce(p_max_chars, 1400), 300);
  v_out  text := '';
  v_line text;
begin
  if coalesce(btrim(p_agent_key),'') = '' then return null; end if;

  -- YOUR NUMBER. attainment mirrors fn_kpi_scoreboard exactly, including the percent_max
  -- inversion; it is NOT recomputed with a different rule, because two rules that must agree is
  -- how sec() and J() ended up with 8 and 11 variants of the same helper.
  -- An unmeasured KPI says so in words. It must never read as a zero.
  select string_agg(
           '- '||z.kpi||': target '||coalesce(z.target_value::text,'?')||' '||coalesce(z.unit,'')
           ||case
               when z.actual_value is null then ' — NOT MEASURED YET (no number exists; do not assume one)'
               else ' — you are at '||z.actual_value::text
                    ||case when z.target_value is null then ''
                    when z.target_value = 0 then
                      case when z.actual_value <= 0 then ', at the zero-defect target (MET)'
                           else ', against a target of ZERO (MISSED)' end
                           when z.unit = 'percent_max'
                             then ', '||round(least(100.0, 100.0 * z.target_value / nullif(z.actual_value,0)),0)::text||'% of target'
                           else ', '||round(100.0 * z.actual_value / z.target_value,0)::text||'% of target' end
                    ||case
                        when z.target_value is null or z.target_value = 0 then ''
                        when z.unit = 'percent_max' then
                          case when z.actual_value <= z.target_value then ' (MET)' else ' (MISSED)' end
                        else
                          case when z.actual_value >= z.target_value then ' (MET)'
                               when z.actual_value >= 0.9 * z.target_value then ' (NEAR)'
                               else ' (MISSED)' end end
             end
           ||case when z.serves_goal is not null then ' — serves company goal '||z.serves_goal else '' end,
           E'\n' order by z.kpi)
    into v_line
    from (select k.kpi, k.target_value, k.unit, k.actual_value, k.serves_goal
            from employee_kpi k
           where k.agent_key = p_agent_key and k.active
           order by k.kpi limit 8) z;

  if v_line is not null then
    v_out := v_out || E'\n# YOUR NUMBER RIGHT NOW — measured, not asserted\n' || v_line || E'\n';
  end if;

  -- YOUR DEPARTMENT'S OBJECTIVE and the company goal it serves. This is the chain the founder
  -- described, delivered to the one employee that has to act on it.
  select string_agg(
           '- '||d.objective
           ||case when d.target_value is not null then ' (target '||d.target_value::text||' '||coalesce(d.unit,'')||')' else '' end
           ||case when d.actual_value is not null then ', department is at '||d.actual_value::text
                  when d.measure_sql is not null then ', not yet measured'
                  else '' end
           ||case when g.key is not null then E'\n    serves company goal '||g.key||' — "'||g.goal||'"' else '' end,
           E'\n' order by d.sort, d.id)
    into v_line
    from department_objective d
    join org_agents a on a.agent_key = p_agent_key and a.department = d.dept_key
    left join company_goals g on g.key = d.goal_key and g.active
   where d.active
   limit 6;

  if v_line is not null then
    v_out := v_out || E'\n# WHAT YOUR DEPARTMENT IS FOR\n' || v_line || E'\n';
  end if;

  if v_out = '' then return null; end if;
  return left(v_out, v_cap);
end $function$;
