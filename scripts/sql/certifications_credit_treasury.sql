-- certifications_credit_treasury.sql
--
-- Why: the founder ruled that every position must sit the top certifications for its role, and that an
-- agent that cannot pass them does not know enough. This file authors the exam question banks for the
-- four credit / treasury / financial-crime certifications carried by the finance department positions:
--   CICM Level 3 Diploma in Credit Management  (collections, rank 1)
--   CCE (Certified Credit Executive)           (collections, rank 2)
--   CTP (Certified Treasury Professional)      (payments_manager, rank 1)
--   CAMS (Certified Anti-Money Laundering Specialist) (payments_manager rank 2, compliance_mgr rank 2)
--
-- 40 questions per bank at real exam difficulty (scenario / application, not definitions), four options,
-- one key, a two-sentence rationale, the syllabus area named as the issuing body names it, 10 of 40
-- marked 'hard' (25%), keys spread exactly 10 A / 10 B / 10 C / 10 D per bank, no all-of-the-above.
-- Up to 5 questions per bank test the UAE variant where the real syllabus covers that ground
-- (Federal Decree-Law 20/2018, Central Bank of the UAE rules, the UN and UAE Local Terrorist lists,
-- the 9% p.a. statutory maximum interest on late commercial payment, card settlement mechanics).
--
-- Each bank is guarded by `where not exists (... where certification = '<name>')` so a bank is authored
-- once even if two authors share a certification; the first author to land wins. The role_certification
-- rows and the sitter are written by a sibling engineer and are deliberately NOT touched here.
--
-- Apply: node scripts/apply_sql.mjs scripts/sql/certifications_credit_treasury.sql --apply --ddl

