comment on function public.fn_accountant_assist(text, vector, numeric, numeric, integer, numeric) is
  'Accountant retrieval over accountant_knowledge and ops_knowledge. A vector-bearing row must clear the cosine floor -- always -- AND corroborate literally, either by the all-terms lexical query or by carrying at least p_min_overlap of the question''s own lexemes verbatim; a row with no vector must clear a stricter lexical-only bar. Returns answered:false with a refusal reason rather than the nearest neighbour, because for a tax question a confident wrong answer is worse than none. Writes nothing, so probing the floor has no production side effect.';

