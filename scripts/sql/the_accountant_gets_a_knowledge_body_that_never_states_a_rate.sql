-- THE ACCOUNTANT GETS A KNOWLEDGE BODY THAT NEVER STATES A RATE
--
-- The founder, 9 Sep 2026, on what the accountant seat must know: "all UAE related financial laws /
-- can pass a CPA test".
--
-- WHAT WAS BUILT AGAINST THAT, AND WHAT WAS DELIBERATELY NOT. There is no supplied pack for this
-- seat -- no ZIP, no JSONL, no manifest from a vendor -- and this session cannot browse the web. So
-- the honest question was what a USEFUL and TRUE knowledge body looks like when you cannot verify a
-- legal fact and must not invent one. The answer this file implements:
--
--   * METHOD IS AUTHORED. Double entry, accrual versus cash, the close sequence, reconciliation,
--     depreciation, revenue recognition for a marketplace fee, how a refund reverses, what an audit
--     trail is. None of that changes when a law is amended, and it is what the seat spends its day
--     doing.
--   * THE SHAPE OF THE UAE OBLIGATIONS IS AUTHORED. That a VAT registration threshold exists and
--     what it is measured against; that corporate tax is a separate regime with its own
--     registration; what a TRN is and what not holding one means; that a record retention
--     obligation exists. The SHAPE, never the figures.
--   * NO FIGURE IS AUTHORED. Not a rate, not a deadline, not a penalty, not a retention period in
--     years, not a threshold amount. Every place a figure would sit, the record says which
--     authority publishes it and how to obtain it. That is the same discipline the Sales Engineer's
--     pack uses, and it is the reason nothing in that pack can go stale.
--   * "CAN PASS A CPA TEST" IS NOT CLAIMED. It is a claim about a certification this body does not
--     hold and cannot self-award. Record QD-ACC-U-005 says so inside the corpus itself, so an agent
--     retrieving from here is told the limits by the corpus rather than only by this comment.
--
-- THE EVALUATION QUESTIONS ARE NOT IN THE CORPUS. scripts/kb/accountant_knowledge_retrieval_eval.mjs
-- holds them, in executable code, and the loader's allowlist admits only records/*.jsonl. The estate
-- has a documented defect where exam answers leaked into the knowledge an agent retrieves and 557
-- rows had to be quarantined; the separation here is structural, not a convention.
--
-- CONSISTENCY WITH public.company_registration IS STRUCTURAL, NOT PROMISED. The records that state
-- the company's own tax position are GENERATED BY THE LOADER from that row every time it runs --
-- vat_registered, trn, vat_threshold_aed, the corporate tax ruling, the auditor ruling. Nothing
-- about the company's position is hand-typed into a JSONL where it could drift from the row, and
-- re-running the loader is what refreshes it. No authored record contradicts those rulings and none
-- generates a request that the founder register for VAT or corporate tax; QD-ACC-U-017 carries his
-- standing instruction not to be asked about corporate tax registration at all.
--
--   node scripts/apply_sql.mjs scripts/sql/the_accountant_gets_a_knowledge_body_that_never_states_a_rate.sql --apply --ddl

-- ---------------------------------------------------------------------------------------------
-- 1. THE KNOWLEDGE BODY
-- ---------------------------------------------------------------------------------------------
-- Its own table, for the reason sales_knowledge has one: a chart-of-accounts record surfacing in a
-- supplier-qualification retrieval is a category error rather than a lucky hit.
--
-- content_sha256 IS ABSENT here and that is deliberate. sales_knowledge carries it because a
-- third-party pack computed its own canonical hash and that token is worth preserving verbatim.
-- This pack is authored in this repository, so there is no second party's hash to preserve, and a
-- second column holding a hash we computed ourselves would prove nothing the first one does not.
create table if not exists public.accountant_knowledge (
  record_id            text primary key,
  record_type          text not null,
  domain               text,
  title                text not null,
  content              text not null,
  structured_data      jsonb not null default '{}'::jsonb,
  source_ids           text[] not null default '{}',
  -- HONEST LABELLING IS A COLUMN, NOT A COMMENT. Six values, each meaning something different
  -- about how far the record may be trusted, and the CHECK stops a seventh being invented by a
  -- later import that finds the taxonomy inconvenient:
  --   method_general_accounting            authored professional method; not jurisdictional, does
  --                                        not go stale when a law changes
  --   marketplace_policy_derived           how THIS company's fees and flows are recorded, derived
  --                                        from its own chart of accounts and published policy
  --   framework_shape_verify_current_text  the shape of an accounting framework's model; the
  --                                        standard's actual current wording must be checked
  --   obligation_shape_no_figures          a UAE obligation described in shape only, containing no
  --                                        rate, deadline, penalty, period or threshold figure
  --   resolve_from_authority               the record EXISTS to say a figure is not held here and
  --                                        to name where it comes from
  --   company_record_generated             generated by the loader from a live table; never typed
  --   company_governance_ruling            a founder ruling about who decides what
  epistemic_status     text not null,
  jurisdiction         text,
  pack_id              text not null,
  pack_version         text not null,
  body_sha256          text not null,
  runtime_index_eligible boolean not null default true,
  authority_effect     text not null default 'none',
  tags                 text[] not null default '{}',
  updated_at           timestamptz,
  ingested_at          timestamptz not null default now(),
  embedding_gte        vector(384),
  search               tsvector,

  -- A knowledge record may DESCRIBE authority. It may never CARRY it. Pinned, not trusted.
  constraint accountant_knowledge_authority_ck check (authority_effect = 'none'),
  constraint accountant_knowledge_epistemic_ck check (epistemic_status in (
    'method_general_accounting', 'marketplace_policy_derived', 'framework_shape_verify_current_text',
    'obligation_shape_no_figures', 'resolve_from_authority', 'company_record_generated',
    'company_governance_ruling', 'authority_protocol'))
);

create index if not exists accountant_knowledge_search_idx on public.accountant_knowledge using gin (search);
create index if not exists accountant_knowledge_type_idx   on public.accountant_knowledge (record_type);
create index if not exists accountant_knowledge_epi_idx    on public.accountant_knowledge (epistemic_status);
create index if not exists accountant_knowledge_emb_hnsw
  on public.accountant_knowledge using hnsw (embedding_gte vector_cosine_ops);

comment on table public.accountant_knowledge is
  'QuotesDone Accountant Knowledge v1 (QD-ACCOUNTANT). Authored accounting method, the SHAPE of UAE financial obligations, and the company''s own recorded position generated from public.company_registration. It states NO tax rate, filing deadline, penalty amount, retention period or threshold figure: where a figure is needed the record says which authority publishes it and how to obtain it. authority_effect is CHECK-pinned to none -- a record may describe authority, never carry it. It is not a certified accounting qualification and no record in it claims to be one.';

comment on column public.accountant_knowledge.epistemic_status is
  'How far the record may be trusted, CHECK-constrained to eight values. obligation_shape_no_figures means a UAE obligation is described in shape only and contains no figure; resolve_from_authority means the record exists to say the figure is NOT held here and to name where it comes from; company_record_generated means the loader wrote it from a live table and it is never hand-typed.';

comment on column public.accountant_knowledge.body_sha256 is
  'sha256 over title || E''\n'' || content. The dedupe key and the change detector: a re-run compares it to decide inserted / updated / unchanged.';

-- The search vector, maintained on write. A trigger rather than a generated column because Postgres
-- will not accept a stored generated column whose expression it cannot prove immutable.
create or replace function public.fn_accountant_knowledge_search_vector()
returns trigger
language plpgsql
set search_path to 'public', 'pg_temp'
as $function$
begin
  new.search :=
      setweight(to_tsvector('english'::regconfig, coalesce(new.title,'')), 'A')
   || setweight(to_tsvector('english'::regconfig, coalesce(array_to_string(new.tags,' '),'')), 'B')
   || setweight(to_tsvector('english'::regconfig, coalesce(new.content,'')), 'C');
  return new;
end $function$;

drop trigger if exists a10_accountant_knowledge_search_vector on public.accountant_knowledge;
create trigger a10_accountant_knowledge_search_vector
  before insert or update of title, tags, content on public.accountant_knowledge
  for each row execute function public.fn_accountant_knowledge_search_vector();

-- ---------------------------------------------------------------------------------------------
-- 2. RETRIEVAL, WITH A FLOOR AND LEXICAL CORROBORATION
-- ---------------------------------------------------------------------------------------------
-- AN UNFILTERED VECTOR SEARCH ALWAYS RETURNS A NEAREST NEIGHBOUR. For a tax question that is not a
-- weak answer, it is a dangerous one: ask "what is the VAT rate" of an unfiltered index and you get
-- the most VAT-shaped passage in the corpus, presented with the same confidence whether or not it
-- answers the question. So the same two-part admission fn_sales_assist uses is applied here.
--
--   * A row WITH an embedding must clear the cosine floor AND corroborate literally. Semantic
--     proximity alone does not admit, ever.
--   * A row WITHOUT an embedding cannot be put to the vector floor at all, so it must clear a
--     stricter lexical-only bar, floored at 0.20 but never below p_min_rank -- tied so that a probe
--     which raises p_min_rank to prove the floor bites closes this route too. A gate nobody can
--     prove fires is not a gate.
--
-- CORROBORATION HAS TWO ROUTES, AND THE SECOND ONE IS HERE BECAUSE THE FIRST WAS MEASURED AND FOUND
-- UNREACHABLE. Built first with the all-terms route alone -- ts_rank against
-- websearch_to_tsquery -- and evaluated over 35 questions an accountant for this company would
-- actually face. Nine were refused. Every one of the nine had the RIGHT record sitting at cosine
-- 0.887 to 0.933 with ts_rank of EXACTLY 0.0000, because websearch_to_tsquery ANDs every term and
-- "what does a trial balance ACTUALLY prove" fails on the adverb. Lowering p_min_rank would have
-- recovered nothing: the rank was not small, it was zero. So the all-terms route is not a
-- corroboration bar for natural-language questions, it is a phrasing lottery.
--
-- The second route is literal lexeme overlap: the row must contain, verbatim, at least
-- p_min_overlap of the question's own content lexemes, and it must STILL clear the cosine floor --
-- the routes are OR-ed with each other and AND-ed with the floor, never instead of it.
--
-- THE THRESHOLD IS 0.60 AND THAT NUMBER IS MEASURED, NOT CHOSEN. fn_sales_assist records that an
-- overlap route at 0.40 was built, applied, measured and REVERTED on its corpus: it admitted a
-- joinery fire-door passage to a supplier-coverage question on 2 lexemes out of 5. That finding is
-- not overridden here, it is respected -- 2/5 is 0.40 and would not clear 0.60. Measured on THIS
-- corpus, 9 Sep 2026:
--   * all 9 previously refused questions carry overlap 0.60 to 0.80 on the correct record
--   * the worst of four nonsense and out-of-scope probes reaches overlap 0.25, at cosine 0.808 --
--     below BOTH gates, so it is refused twice over
--   * every row the new route additionally admits was topically correct on inspection: the
--     processing-fee question admits both account 6100 and the Stripe clearing record, and the
--     journal-correction question admits both the correction record and the entry-requirements one
-- A short question cannot slip through on one common word: the requirement is the greater of 60%
-- and two lexemes, so a 3-lexeme question needs 2 and an 8-lexeme one needs 5.
--
-- THIS FUNCTION WRITES NOTHING. fn_sales_assist records a gap and opens a task on a refusal; that
-- is the right design for a portal question from a customer who is waiting. It is the wrong design
-- here, because it makes every probe of the floor a production write and this estate has already
-- been bitten by rehearsals that paged the founder. The refusal is returned to the caller, which
-- owns what to do with it.
-- ponytail: no gap table and no task on refusal. Add one when there is a live caller whose
-- unanswered questions need counting across sessions; the eval script measures coverage today.
-- The signature gains p_min_overlap, so the old five-argument form is dropped rather than left
-- beside it: two overloads differing only by a defaulted trailing argument make every existing
-- five-argument call ambiguous, and Postgres reports that at call time rather than at create time.
drop function if exists public.fn_accountant_assist(text, vector, numeric, numeric, integer);

create or replace function public.fn_accountant_assist(
  p_text            text,
  p_embedding       vector default null,
  p_min_similarity  numeric default 0.86,
  p_min_rank        numeric default 0.05,
  p_k               integer default 5,
  p_min_overlap     numeric default 0.60)
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $function$
declare
  v_k         int := greatest(1, least(coalesce(p_k, 5), 20));
  v_wide      int := greatest(v_k * 4, 20);
  c_lex_only  numeric := greatest(0.20, coalesce(p_min_rank, 0));
  v_tq        tsquery;
  v_lex       text[];
  v_nlex      int;
  v_need      int;
  v_cands     jsonb  := '[]'::jsonb;
  v_cited     text[] := '{}';
  v_answer    jsonb  := '[]'::jsonb;
  v_refusal   text;
  v_best_sim  numeric;
  v_best_rank numeric;
  v_best_lex  int;
  v_best_corp text;
  v_handoff   text;
begin
  if coalesce(btrim(p_text), '') = '' then
    return jsonb_build_object('ok', false, 'answered', false, 'refusal', 'empty_query');
  end if;

  v_tq := websearch_to_tsquery('english', p_text);
  select array_agg(distinct u.lexeme) into v_lex from unnest(to_tsvector('english', p_text)) u;
  v_nlex := coalesce(cardinality(v_lex), 0);
  -- The greater of 60% and two lexemes, so a short question cannot be admitted on one common word.
  v_need := case when v_nlex = 0 then 2147483647
                 else greatest(least(2, v_nlex), ceil(coalesce(p_min_overlap, 0.60) * v_nlex)::int) end;

  create temporary table if not exists _aa_cand (
    corpus text, record_id text, title text, content text, provenance text,
    similarity numeric, lexical_rank numeric, has_vector boolean, lex_hits int default 0
  ) on commit drop;
  -- truncate, not delete: the estate refuses an unqualified DELETE and a WHERE-less delete on a
  -- scratch table is exactly what that guard exists to catch elsewhere.
  truncate table _aa_cand;

  -- accountant_knowledge -- the seat's own body.
  if p_embedding is not null then
    insert into _aa_cand
    select 'accountant_knowledge', k.record_id, k.title, left(k.content, 4000),
           coalesce(k.record_type, '') || case when k.domain is null then '' else ' · ' || k.domain end
             || ' · ' || k.epistemic_status,
           (1 - (k.embedding_gte <=> p_embedding))::numeric,
           coalesce(ts_rank(k.search, v_tq), 0)::numeric * (case when k.search @@ v_tq then 1 else 0 end),
           true,
           (select count(*) from unnest(k.search) u where u.lexeme = any (v_lex))
      from accountant_knowledge k
     where k.embedding_gte is not null and k.runtime_index_eligible
     order by k.embedding_gte <=> p_embedding
     limit v_wide;
  end if;
  insert into _aa_cand
  select 'accountant_knowledge', k.record_id, k.title, left(k.content, 4000),
         coalesce(k.record_type, '') || ' · ' || k.epistemic_status,
         null::numeric, ts_rank(k.search, v_tq)::numeric, false, 0
    from accountant_knowledge k
   where k.embedding_gte is null and k.runtime_index_eligible and k.search @@ v_tq
   order by ts_rank(k.search, v_tq) desc
   limit v_wide;

  -- ops_knowledge -- how this company actually operates. A finance question frequently turns on a
  -- company rule rather than on accounting, and a seat that cannot see those answers half a
  -- question. Superseded rows are excluded: never quote a rule that has been replaced.
  if p_embedding is not null then
    insert into _aa_cand
    select 'ops_knowledge', o.record_id, o.title, left(o.content, 4000),
           coalesce(o.record_type, '') || case when o.authority_tier is null then '' else ' · authority ' || o.authority_tier end,
           (1 - (o.embedding_gte <=> p_embedding))::numeric,
           coalesce(ts_rank(o.tsv, v_tq), 0)::numeric * (case when o.tsv @@ v_tq then 1 else 0 end),
           true,
           (select count(*) from unnest(o.tsv) u where u.lexeme = any (v_lex))
      from ops_knowledge o
     where o.embedding_gte is not null
       and coalesce(o.supersession_state, 'current') = 'current'
     order by o.embedding_gte <=> p_embedding
     limit v_wide;
  end if;

  -- ADMISSION. The cosine floor is a hard AND for every vector-bearing row; corroboration may come
  -- from either the all-terms rank or literal lexeme overlap, and one of the two is required.
  with judged as (
    select c.*,
           (c.has_vector and c.similarity >= p_min_similarity
             and (c.lexical_rank >= p_min_rank or c.lex_hits >= v_need))     as ok_vector,
           ((not c.has_vector) and c.lexical_rank >= c_lex_only)             as ok_lexical
      from _aa_cand c
  ), ranked as (
    select j.*, (j.ok_vector or j.ok_lexical) as cited,
           row_number() over (
             order by (case when j.ok_vector or j.ok_lexical then 0 else 1 end),
                      (case when j.has_vector then 0 else 1 end),
                      j.similarity desc nulls last, j.lexical_rank desc) as rn
      from judged j
  )
  select
    coalesce(jsonb_agg(jsonb_build_object(
      'corpus', r.corpus, 'record_id', r.record_id,
      'similarity', round(r.similarity, 4), 'lexical_rank', round(r.lexical_rank, 4),
      'route', case when r.has_vector then 'vector+lexical' else 'lexical_only' end,
      'cleared_floor', coalesce(r.has_vector and r.similarity >= p_min_similarity, false),
      'lex_hits', r.lex_hits, 'lex_needed', v_need,
      'corroborated', case when r.has_vector then (r.lexical_rank >= p_min_rank or r.lex_hits >= v_need)
                           else r.lexical_rank >= c_lex_only end,
      'cited', r.cited) order by r.rn) filter (where r.rn <= 40), '[]'::jsonb),
    coalesce(array_agg(r.corpus || ':' || r.record_id order by r.rn)
             filter (where r.cited and r.rn <= v_k), '{}'),
    coalesce(jsonb_agg(jsonb_build_object(
      'corpus', r.corpus, 'record_id', r.record_id, 'title', r.title,
      'provenance', r.provenance,
      'similarity', round(r.similarity, 4), 'lexical_rank', round(r.lexical_rank, 4),
      'route', case when r.has_vector then 'vector+lexical' else 'lexical_only' end,
      'content', r.content) order by r.rn) filter (where r.cited and r.rn <= v_k), '[]'::jsonb)
    into v_cands, v_cited, v_answer
    from ranked r;

  select max(similarity), max(lexical_rank), max(lex_hits)
    into v_best_sim, v_best_rank, v_best_lex from _aa_cand;
  select corpus into v_best_corp from _aa_cand
   order by similarity desc nulls last, lexical_rank desc limit 1;

  if cardinality(v_cited) = 0 then
    v_refusal := case
      when (select count(*) from _aa_cand) = 0 then 'no_candidates'
      when coalesce(v_best_sim, 0) < p_min_similarity and coalesce(v_best_rank, 0) < c_lex_only
        then 'below_similarity_floor_and_lexical_bar'
      when coalesce(v_best_sim, 0) < p_min_similarity then 'below_similarity_floor'
      else 'not_corroborated_lexically' end;
    v_handoff :=
      'I do not have a sourced answer to that, and I will not guess at a financial or tax question. '
      || 'If it needs a rate, a threshold, a deadline or a penalty, that figure is deliberately not '
      || 'held in my knowledge: it is published by the Federal Tax Authority and must be read from '
      || 'its current publication for the period concerned.';
  end if;

  return jsonb_build_object(
    'ok', true,
    'answered', cardinality(v_cited) > 0,
    'records', v_answer,
    'cited', v_cited,
    'candidates', v_cands,
    'corpora', jsonb_build_array('accountant_knowledge', 'ops_knowledge'),
    'floor', jsonb_build_object(
      'min_similarity', p_min_similarity, 'min_rank', p_min_rank, 'lexical_only', c_lex_only,
      'min_overlap', p_min_overlap, 'lexemes_in_question', v_nlex, 'lexeme_overlap_needed', v_need,
      'best_similarity', round(v_best_sim, 4), 'best_lexical_rank', round(v_best_rank, 4),
      'best_lex_hits', v_best_lex, 'nearest_corpus', v_best_corp, 'k', v_k,
      'rule', 'a row with an embedding must clear the cosine floor -- always -- AND corroborate literally by one of two routes: the all-terms lexical query at ts_rank >= min_rank, or at least lexeme_overlap_needed of the question''s own lexemes present verbatim in the row. The overlap route exists because the all-terms route was measured at exactly ts_rank 0.0000 on 9 of 35 realistic questions whose correct record sat at cosine 0.887-0.933: websearch_to_tsquery ANDs every term, so one filler adverb defeats it. A row with no embedding cannot be put to the vector floor at all and must clear the stricter lexical-only bar instead. A nearest neighbour is always found; a literal match is not.'),
    'refusal', v_refusal,
    'handoff', v_handoff);
end
$function$;

