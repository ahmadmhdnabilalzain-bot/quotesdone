-- THREE VIEWS WERE READABLE BY EVERY LOGGED-IN USER AND READ BY NOBODY.
--
-- The estate's own security_selfaudit_daily has been raising this every morning:
--
--   "Security drift: public data reachable by anon — anon_readable_views=3,
--    anon_readable_tables=1, anon_executable_secdef_fns=63"
--
-- THE ALERT IS MISLABELLED, AND THE MISLABEL MATTERS. fn_security_selfaudit counts
-- `has_table_privilege('anon',...) OR has_table_privilege('authenticated',...)`, but the alert says
-- "reachable by anon". Measured: NONE of the four objects is anon-readable. All four are
-- `authenticated` only. Public exposure and logged-in exposure are different severities, and an
-- alert that overstates one as the other gets ignored — or panicked over — for the wrong reason.
--
--   documents             table  anon=false authed=true  RLS ON  -> policies govern it, left alone
--   v_customer_master     view   anon=false authed=true  no RLS  -> revoked here
--   v_kb_coverage         view   anon=false authed=true  no RLS  -> revoked here
--   v_supplier_doc_score  view   anon=false authed=true  no RLS  -> revoked here
--
-- WHY THE VIEWS ARE THE REAL RISK AND THE TABLE IS NOT. `documents` has row-level security enabled,
-- so an authenticated user sees only the rows policy allows. A VIEW is not RLS-protected: none of
-- these three is `security_invoker`, so each runs with its owner's rights and reads straight past
-- the RLS on its base tables. v_customer_master is a customer master. It is harmless *today* only
-- because public.customers holds zero rows — the day a real customer registers, every logged-in
-- user on the platform can read the customer master.
--
-- SAFE TO REVOKE — verified rather than assumed:
--   v_customer_master     0 readers anywhere: no src/, no edge function, no database function
--   v_kb_coverage         read only by fn_ws_knowledge, which is SECURITY DEFINER and which
--                         `authenticated` cannot even EXECUTE — it reads the view as owner
--   v_supplier_doc_score  read only by one edge function, which uses the service role key
-- Nothing reaches these views as the `authenticated` role, so removing that grant removes access
-- nobody was using.
--
-- Left for the founder, deliberately: anon_executable_secdef_fns=63. Sixty-three SECURITY DEFINER
-- functions are EXECUTE-able by anon. That is the largest number in the alert and the one that
-- actually concerns public exposure, but revoking sixty-three grants blind is how a working product
-- surface breaks. It needs a caller-by-caller pass, not a sweep.

revoke select on public.v_customer_master    from authenticated, anon;
revoke select on public.v_kb_coverage        from authenticated, anon;
revoke select on public.v_supplier_doc_score from authenticated, anon;
