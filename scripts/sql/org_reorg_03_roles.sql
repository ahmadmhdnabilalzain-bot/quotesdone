insert into public.org_role (
  role_id, display_name, primary_department_id, manager_role_id, runtime_mode, runtime_agent_key,
  responsibilities, owned_decisions, forbidden_decisions, activation_conditions,
  required_inputs, output_contracts, tools, knowledge_scopes, authority_level, budget_limit,
  handoff_targets, escalation_targets, model_policy, evaluation_suite, status,
  source_agent_keys, rationale)
select
  d.role_id, d.display_name, a.department, null, d.runtime_mode, d.agent_key,
  coalesce(nullif(split_part(a.responsibilities, e'\n', 1), ''), d.display_name),
  d.owned, d.forbidden, d.activation,
  coalesce((select array_agg(w.workflow_key order by w.workflow_key)
              from public.employee_workflow w where w.agent_key = d.agent_key), '{}'),
  d.outputs,
  coalesce((select array_agg(distinct x.action_class)
              from public.org_action_executor x
             where x.active and (x.department = a.department or x.target = d.agent_key)), '{}'),
  coalesce((select array_agg(distinct k.domain_key)
              from public.employee_knowledge k where k.agent_key = d.agent_key), '{}')
    || public.fn_dept_scope(a.department),
  d.authority_level,
  (select max(y.threshold_aed) from public.employee_authority y where y.agent_key = d.agent_key),
  '{}', '{}',
  coalesce(a.routing_tier, 'operations_specialist'),
  d.evaluation, 'active',
  array[d.agent_key], d.rationale
from _role_driver d
join public.org_agents a on a.agent_key = d.agent_key and a.active
on conflict (role_id) do update set
  display_name = excluded.display_name,
  primary_department_id = excluded.primary_department_id,
  runtime_mode = excluded.runtime_mode,
  runtime_agent_key = excluded.runtime_agent_key,
  owned_decisions = excluded.owned_decisions,
  forbidden_decisions = excluded.forbidden_decisions,
  activation_conditions = excluded.activation_conditions,
  required_inputs = excluded.required_inputs,
  output_contracts = excluded.output_contracts,
