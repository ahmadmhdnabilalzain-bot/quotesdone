-- REORGANISING THE AGENT COMPANY — 3 of 5: the canonical role registry.
--
-- 90 accountable roles and 86 category overlays, each with one primary department, one primary
-- manager, a runtime mode, owned and forbidden decisions, activation conditions, tools, knowledge,
-- authority, handoff and escalation targets, and a named evaluation suite.
--
-- Authored here: role_id, display name, runtime mode, authority level, activation, owned and
-- forbidden decisions, output contract, evaluation suite. Derived from live tables: manager (from
-- org_agents.manager_key mapped through this same registry), tools (org_action_executor the role
-- can actually execute), knowledge scopes (employee_knowledge + the department scope), required
-- inputs (employee_workflow), model policy (routing tier), budget limit (employee_authority).
-- Deriving those means the registry cannot claim a tool or a knowledge domain the runtime does not
-- actually grant.

