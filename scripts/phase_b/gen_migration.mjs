{
  const lines = [HEAD('teach the organization the names the estate already uses'), `
-- org_role_alias carries NO Phase A frozen digest and NO z90_phase_a_freeze trigger.  Adding an
-- alias teaches the estate a second name for an EXISTING employee; it creates, renames, merges,
-- moves and retires nothing, and fn_phase_a_baseline_drift() stays at zero rows.
--
-- Two populations:
--   * packaged_role_id — the Phase B package addresses roles descriptively
--     ("payments_billing_manager"); Phase A stores them as "payments_and_billing_manager".
--   * title — public.workflow_step.actor_role holds human-readable titles for 74 of its 184
--     rows, which is why 40% of current runtime step ownership resolves to nobody today.
--
-- Every insert below is guarded on the target role being ACTIVE, so a typo inserts nothing
-- rather than binding work to a role that does not exist.
`];

  const emit = (alias, roleId, kind, reason) => lines.push(
    `insert into public.org_role_alias (alias, role_id, kind, reason)
select ${qs(alias)}, ${qs(roleId)}, ${qs(kind)}, ${qs(reason)}
where exists (select 1 from public.org_role where role_id = ${qs(roleId)} and status = 'active')
on conflict (alias) do nothing;`);

  lines.push('\n-- ---- packaged_role_id: the Phase B package spelling ----');
  for (const [alias, roleId] of Object.entries(PACKAGE_ROLE_ALIASES).sort()) {
    emit(alias, roleId, 'packaged_role_id', 'Phase B package addresses this role by descriptive name');
  }
  lines.push('\n-- ---- title: the spelling on public.workflow_step.actor_role ----');
  for (const [alias, [roleId, basis]] of Object.entries(TITLE_ALIASES).sort()) {
    emit(alias, roleId, 'title', `Phase B reconciliation: ${basis}`);
  }
  writeFileSync(join(SQL_DIR, 'phase_b_02_identity_aliases.sql'), lines.join('\n') + '\n', 'utf8');
}

