// =====================================================================================
// 07 — the crosswalk
// =====================================================================================
{
  const rows = parseCSV(readFileSync(
    join(REPO, 'docs', 'phase-b', 'PHASE_B_CURRENT_TO_TARGET_WORKFLOW_CROSSWALK.csv'), 'utf8'));
  const hdr = rows[0];
  const L = [HEAD('the current-estate crosswalk')];
  L.push(`
-- ${rows.length - 1} measured rows.  Loading them changes no behaviour; it puts the measurement
-- where Phase C can read it, with the command that produced each verdict alongside it.`);
  const COLS = ['current_artifact_type', 'current_artifact_name', 'repository_or_database_location',
    'current_trigger_or_caller', 'current_owner_or_actor', 'current_states_or_outcomes',
    'target_workflow_id', 'target_step_id', 'target_classification', 'duplicate_or_conflicting_path',
    'historical_compatibility_required', 'phase_c_wiring_action', 'evidence_command',
    'evidence_result', 'notes'];
  L.push(insertMany('phase_b_crosswalk', COLS,
    rows.slice(1).map(r => {
      const o = Object.fromEntries(hdr.map((h, i) => [h, r[i] ?? '']));
      return COLS.map(c => qs(o[c]));
    }), ['current_artifact_type', 'current_artifact_name']));
  writeFileSync(join(SQL_DIR, 'phase_b_07_crosswalk.sql'), L.join('\n') + '\n', 'utf8');
}

