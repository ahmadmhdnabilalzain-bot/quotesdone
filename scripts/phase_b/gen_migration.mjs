// Generate the Phase B forward migration and its exact rollback from the committed package.
//
//   node scripts/phase_b/gen_migration.mjs
//
// The SQL is generated rather than hand-written so the files and the package cannot drift:
// re-running this must produce byte-identical output, and the deterministic test suite checks
// exactly that.  Errata are applied here, once, from lib/identity.mjs.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { REPO, loadPackage, splitList, parseCSV } from './lib/package.mjs';
import { readFileSync } from 'node:fs';
import {
  PACKAGE_ROLE_ALIASES, DYNAMIC_ACTORS, NON_ACCOUNTABLE_ACTORS, PACKAGE_ERRATA, isClosureStep,
} from './lib/identity.mjs';

const SQL_DIR = join(REPO, 'scripts', 'sql');
const q = v => v === null || v === undefined || v === '' ? 'null' : `'${String(v).replace(/'/g, "''")}'`;
const qn = v => v === null || v === undefined || v === '' ? 'null' : `'${String(v).replace(/'/g, "''")}'`;
const qs = v => `'${String(v ?? '').replace(/'/g, "''")}'`;           // never null
const arr = list => list.length
  ? `array[${list.map(qs).join(',')}]::text[]` : `'{}'::text[]`;
const bool = v => /^(yes|true|1)$/i.test(String(v ?? '')) ? 'true' : 'false';

/**
 * One statement per table, not one per row.
 *
 * A row-at-a-time file reached 606 KB for the 257 steps alone, because the ON CONFLICT clause
 * was repeated 257 times.  The management API posts a file as a single request, so the size
 * matters: this emits `insert ... values (...),(...) on conflict ... do update` once per table
 * and cuts the same content to a fraction, while staying one implicit transaction.
 */
function insertMany(table, columns, rows, conflictKey) {
  if (!rows.length) return '';
  const set = columns.filter(c => !conflictKey.includes(c))
    .map(c => `${c} = excluded.${c}`).join(', ');
  return `insert into public.${table} (${columns.join(', ')}) values\n`
    + rows.map(r => `  (${r.join(', ')})`).join(',\n')
    + `\non conflict (${conflictKey.join(', ')}) do update set ${set};`;
}

const HEAD = title => `-- Phase B — ${title}
--
-- Generated by scripts/phase_b/gen_migration.mjs from the checksummed package under
-- docs/phase-b/package/.  Do not hand-edit: scripts/checks/phase_b_migration_matches_package.test.mjs
-- regenerates this file and fails on any difference.
--
-- This file writes registry rows only.  It creates no cron job, no provider route, no
-- autonomous executor and no business record.

set lock_timeout = '8s';
set statement_timeout = '600s';
`;

// ---------------------------------------------------------------------- load + errata
const pkg = loadPackage();
for (const e of PACKAGE_ERRATA) {
  const row = e.file === 'PHASE_B_EXCEPTION_ESCALATION_MATRIX.csv'
      ? pkg.exceptions.find(x => x.exception_id === e.id)
    : e.file === 'PHASE_B_WORKFLOW_REGISTRY.csv'
      ? pkg.workflows.find(x => x.workflow_id === e.id)
    : pkg.steps.find(x => x.step_id === e.id);
  if (!row) throw new Error(`erratum target ${e.id} not found`);
  Object.assign(row, e.correction);
}

// -------------------------------------------------------------- role token resolution
// Package token -> canonical role_id.  Tokens already equal to a canonical role_id pass through;
// the alias map covers the descriptive names; dynamic actors are returned untouched.
const RESOLVE = tok => {
  const t = String(tok ?? '').trim();
  if (!t) return '';
  if (DYNAMIC_ACTORS[t]) return t;
  return PACKAGE_ROLE_ALIASES[t] ?? t;
};
const resolveList = cell => splitList(cell).map(RESOLVE).filter(Boolean);

const actorKind = tok => tok === 'founder' ? 'founder'
  : tok === 'relevant_category_overlay' ? 'category_overlay'
  : 'canonical_role';

