// Generate scripts/sql/what_if_result_carries_confidence.sql — the simulation's confidence goes in
// the result the caller reads, not only in the question it was asked.
//
// MEASURED, production 11 Aug 2026: fn_what_if computes v_conf on every branch and writes it into
// `scenario`, beside the question and the change. `result` — the projection a caller actually reads
// and the column what-if-confidence-score scores — does not carry it:
//
//   insert into simulations (scenario, result)
//   values (jsonb_build_object('question',p_question,'change',p_change,'confidence',v_conf), v_impact)
//
// So `simulations` reads 3 of 6 carrying a confidence in the result, and the three that do are from
// 6 July, when the projection happened to build the key into v_impact by hand. Every simulation
// since has computed a confidence and then filed it where the reader does not look.
//
// This is not a new number. v_conf is the score the simulator already assigned to the branch it
// took, and it is already returned to the caller in the jsonb_build_object at the end of the
// function; it simply never reached the stored row. Merging it into the result makes the stored
// projection and the returned projection the same object.
//
// The check does not go green: it is a universal over the whole simulations table with no time
// window, and the three July rows without the key are permanent. Fixing the writer is still right,
// and it stops every future simulation from making the ratio worse — which is what my own
// simulation #8 did before this.
//
//   node scripts/gen_what_if_result_carries_confidence.mjs
//   node scripts/apply_sql.mjs scripts/sql/what_if_result_carries_confidence.sql --promote
import { writeFileSync } from 'node:fs';
import { mgmtRead, PROD_REF } from './staging/qd_guard.mjs';

const ANCHOR = `values (jsonb_build_object('question',p_question,'change',p_change,'confidence',v_conf), v_impact)`;
const REPL = `values (jsonb_build_object('question',p_question,'change',p_change,'confidence',v_conf),
          -- The confidence belongs in the projection the caller reads, not only beside the question
          -- it was asked. coalesce guards the branch that builds it by hand already.
          v_impact || jsonb_build_object('confidence', coalesce((v_impact->>'confidence')::numeric, v_conf)))`;

const rows = await mgmtRead(
  PROD_REF,
  `select pg_get_functiondef(p.oid) as def from pg_proc p join pg_namespace n on n.oid=p.pronamespace
    where n.nspname='public' and p.proname='fn_what_if'`,
);
const def = rows?.[0]?.def;
if (!def) { console.error('fn_what_if not found'); process.exit(1); }
if (/v_impact \|\| jsonb_build_object\('confidence'/.test(def)) { console.log('SKIP already merged'); process.exit(0); }
const hits = def.split(ANCHOR).length - 1;
if (hits !== 1) { console.error(`ANCHOR found ${hits} time(s), expected exactly 1 — refusing`); process.exit(1); }

writeFileSync(
  'scripts/sql/what_if_result_carries_confidence.sql',
  [
    `-- GENERATED by scripts/gen_what_if_result_carries_confidence.mjs — do not hand-edit.`,
    `--`,
    `-- fn_what_if computed a confidence on every branch and filed it in \`scenario\`, beside the`,
    `-- question, while \`result\` — the projection the caller reads — carried none. The stored`,
    `-- projection and the returned projection are now the same object.`,
    ``,
    def.replace(ANCHOR, REPL).trimEnd() + ';',
    ``,
  ].join('\n'),
);
console.log('OK   fn_what_if result now carries the confidence\nwrote scripts/sql/what_if_result_carries_confidence.sql');
