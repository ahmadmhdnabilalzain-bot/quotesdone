// Matching accuracy: precision and recall of public.fn_match_capability on a labelled ZZ DEMO set.
// Seat: sales_engineer. 28 Sep 2026.
//
//   node scripts/eval/matching_accuracy_eval.mjs              # offline: scorer self-check + the set's shape
//   node scripts/eval/matching_accuracy_eval.mjs --emit       # print the aborted-transaction probe SQL
//   node scripts/eval/matching_accuracy_eval.mjs --run <ref>  # run the probe on a NON-production ref, score it
//
// The probe inserts the fixture suppliers inside a block that always ends in a raised exception, so every
// row rolls back (pattern: a_supplier_who_limits_its_emirates_is_matched_only_there_probe.sql). What
// survives is one verdict row carrying, per inquiry, the fixture suppliers the real routine returned.
// --run goes through mgmtWrite, which refuses the production ref: a rolled-back write is still a write.
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';

const SET = JSON.parse(readFileSync(new URL('../fixtures/zz_demo_matching_accuracy_set.json', import.meta.url), 'utf8'));

// Micro-averaged over every (inquiry, supplier) pair. An empty expectation that returns nothing is correct
// and adds nothing to either denominator; precision with nothing returned is 1 (nothing wrong was said).
export function score(expected, got) {
  let tp = 0, fp = 0, fn = 0; const misses = [];
  for (const [k, exp] of Object.entries(expected)) {
    const e = new Set(exp), g = new Set(got[k] || []);
    for (const s of g) if (e.has(s)) tp++; else { fp++; misses.push(`${k}: extra ${s}`); }
    for (const s of e) if (!g.has(s)) { fn++; misses.push(`${k}: missed ${s}`); }
  }
  const r3 = (x) => Math.round(x * 1000) / 1000;
  return { tp, fp, fn, precision: r3(tp + fp ? tp / (tp + fp) : 1), recall: r3(tp + fn ? tp / (tp + fn) : 1), misses };
}

const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (a) => `array[${a.map(lit).join(',')}]::text[]`;

export function probeSql(set = SET) {
  const ins = set.suppliers.map((s) => `
    insert into public.leads (company_name, email, emirate, sector, phone, owner_phone_verified, owner_email_verified,
                              license_doc_path, company_profile_doc_path, signed_terms_path, verified, approval_status, service_emirates)
    values (${lit('ZZ DEMO — match ' + s.key)}, ${lit('zz.demo.match.' + s.key + '@example.invalid')}, ${lit(s.emirates[0] || 'Dubai')},
            ${lit(s.trades[0])}, ${lit(s.phone)}, true, true, v_lic, v_prof, 'suppliers/zz-demo-match.pdf', true, 'approved',
            ${s.emirates.length ? arr(s.emirates) : 'null'})
    returning id into v_id;
    insert into public.supplier_capabilities (supplier_id, trades, roles, coverage_emirates, confirmed_at)
    values (v_id, ${arr(s.trades)}, ${arr(s.roles)}, ${arr(s.emirates)}, now());
    v_keys := v_keys || jsonb_build_object(v_id::text, ${lit(s.key)});`).join('');
  const runs = set.inquiries.map((q) => `
    v_got := v_got || jsonb_build_object(${lit(q.key)}, (select coalesce(jsonb_agg(v_keys ->> m.supplier_id::text order by m.supplier_id), '[]')
      from public.fn_match_capability(${arr(q.trades)}, 'executes', p_emirate => ${lit(q.emirate)}, p_limit => 500) m
     where v_keys ? m.supplier_id::text));`).join('');
  return `-- generated by scripts/eval/matching_accuracy_eval.mjs from scripts/fixtures/zz_demo_matching_accuracy_set.json
begin;
do $$
declare
  v_id bigint; v_keys jsonb := '{}'; v_got jsonb := '{}'; v_left int;
  v_lic text := 'zz-demo/match-accuracy-licence.pdf'; v_prof text := 'zz-demo/match-accuracy-profile.pdf';
begin
  set local statement_timeout = '20s';
  begin
    insert into storage.objects (bucket_id, name)
      select 'supplier-docs', n from unnest(array[v_lic, v_prof]) n
       where not exists (select 1 from storage.objects o where o.bucket_id = 'supplier-docs' and o.name = n);${ins}${runs}
    raise exception 'ROLLBACK_PROBE';
  exception when others then
    if sqlerrm <> 'ROLLBACK_PROBE' then raise; end if;
  end;
  select count(*) into v_left from public.leads where email like 'zz.demo.match.%@example.invalid';
  if v_left <> 0 then raise exception 'the rollback left % fixture suppliers behind', v_left; end if;
  perform set_config('qd.probe_verdict', 'PROBE OK ' || v_got::text, true);
exception when others then
  perform set_config('qd.probe_verdict', 'PROBE FAILED ' || sqlerrm, true);
end $$;
select coalesce(current_setting('qd.probe_verdict', true), 'PROBE FAILED (no verdict)') as verdict;
commit;
`;
}

const expected = Object.fromEntries(SET.inquiries.map((q) => [q.key, q.expected]));

function selfCheck() {
  const keys = new Set(SET.suppliers.map((s) => s.key));
  for (const q of SET.inquiries) for (const e of q.expected) assert.ok(keys.has(e), `${q.key} expects unknown supplier ${e}`);
  for (const s of SET.suppliers) assert.match(s.phone, /^\+9715000000\d\d$/, `${s.key} phone is outside the fixture block`);
  assert.deepEqual(score(expected, expected).misses, []);
  const perfect = score(expected, expected);
  assert.equal(perfect.precision, 1); assert.equal(perfect.recall, 1);
  const bad = score({ a: ['x', 'y'], b: [] }, { a: ['x', 'z'], b: ['w'] });
  assert.deepEqual([bad.tp, bad.fp, bad.fn, bad.precision, bad.recall], [1, 2, 1, 0.333, 0.5]);
  assert.ok(probeSql().includes("raise exception 'ROLLBACK_PROBE'"));
  const pairs = SET.inquiries.reduce((n, q) => n + q.expected.length, 0);
  console.log(`OFFLINE OK: ${SET.suppliers.length} ZZ DEMO suppliers, ${SET.inquiries.length} inquiries, ${pairs} labelled pairs; scorer self-check passed`);
}

const argv = process.argv.slice(2);
if (argv[0] === '--emit') process.stdout.write(probeSql());
else if (argv[0] === '--run') {
  const { mgmtWrite } = await import('../lib/qd_guard.mjs');
  const rows = await mgmtWrite(argv[1], probeSql(), 'matching accuracy probe');
  const v = String(rows?.[rows.length - 1]?.verdict ?? rows?.[0]?.verdict ?? '');
  if (!v.startsWith('PROBE OK ')) { console.error(v || JSON.stringify(rows)); process.exit(3); }
  const s = score(expected, JSON.parse(v.slice('PROBE OK '.length)));
  console.log(JSON.stringify(s, null, 1));
} else selfCheck();
