// THE SENIOR STANDARD, AS ROWS THE DATABASE CAN MEASURE AGAINST (ceo, 27 Oct 2026; founder ledger 1003).
//
// The standard lives in the repository (knowledge/standards/<seat>.json: what a senior hire would contribute, and which
// seat_duty keys make each contribution; knowledge/exams/<seat>.json and knowledge/exams/judged/<seat>.json: the exam and
// the reader's verdict on each answer). The weekly verdict (fn_ceo_seat_senior_verdict) runs in the database, which
// cannot read the repository, so the SQL file carries both as seed rows between two markers. This script writes that
// block; scripts/checks/the_senior_verdict_is_measured_against_the_standard_in_the_repository.test.mjs fails when the
// block and the files part.
//
//   node scripts/eval/seat_senior_standard_seed.mjs           # print the block
//   node scripts/eval/seat_senior_standard_seed.mjs --write   # replace it in the SQL file
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const SQL_FILE = 'scripts/sql/the_ceo_measures_every_seat_against_its_senior_standard_every_week.sql';
export const BEGIN = '-- BEGIN STANDARD SEED (generated by scripts/eval/seat_senior_standard_seed.mjs; do not edit by hand)';
export const END = '-- END STANDARD SEED';
// The judged exam's date: knowledge/exams/judged/<seat>.json was read on 19 Oct 2026 (the 2026-10-19-after run).
export const JUDGED_ON = '2026-10-19';

const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (a) => `array[${a.map(lit).join(', ')}]::text[]`;

export function seedBlock(repo = REPO) {
  const read = (p) => JSON.parse(readFileSync(join(repo, p), 'utf8'));
  const seats = readdirSync(join(repo, 'knowledge', 'standards')).filter((f) => f.endsWith('.json')).map((f) => f.slice(0, -5)).sort();
  const contrib = []; const exams = [];
  for (const seat of seats) {
    const std = read(`knowledge/standards/${seat}.json`);
    for (const c of std.contributions) contrib.push(`  (${lit(seat)}, ${lit(c.id)}, ${lit(c.what)}, ${arr(c.duties ?? [])})`);
    const exam = read(`knowledge/exams/${seat}.json`);
    const jf = `knowledge/exams/judged/${seat}.json`;
    if (existsSync(join(repo, jf))) {
      const judged = read(jf);
      exams.push(`  (${lit(seat)}, date ${lit(JUDGED_ON)}, ${exam.items.length}, ${judged.items.filter((i) => i.verdict === 'pass').length}, ${lit(jf)})`);
    }
  }
  return [
    BEGIN,
    // the seed replaces each seat's contributions whole, so one dropped from a standard leaves the table too
    `delete from public.seat_senior_contribution where seat = any (${arr(seats)});`,
    'insert into public.seat_senior_contribution (seat, contribution_id, what, duties) values',
    contrib.join(',\n') + ';',
    'insert into public.seat_senior_exam (seat, judged_on, items, passed, source) values',
    exams.join(',\n'),
    'on conflict (seat, judged_on) do update set items = excluded.items, passed = excluded.passed, source = excluded.source;',
    END,
  ].join('\n');
}

export function currentBlock(text) {
  const a = text.indexOf(BEGIN); const b = text.indexOf(END);
  return a < 0 || b < 0 ? null : text.slice(a, b + END.length);
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const block = seedBlock();
  if (!process.argv.includes('--write')) { console.log(block); process.exit(0); }
  const path = join(REPO, SQL_FILE);
  const text = readFileSync(path, 'utf8');
  const cur = currentBlock(text);
  if (!cur) { console.error(`${SQL_FILE} has no seed markers`); process.exit(1); }
  writeFileSync(path, text.replace(cur, block));
  console.log(`seed block written to ${SQL_FILE}`);
}
