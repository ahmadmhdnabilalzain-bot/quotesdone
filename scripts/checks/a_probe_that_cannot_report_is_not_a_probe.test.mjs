// A PROBE THAT CANNOT REPORT IS NOT A PROBE.
//
// quotesdone-apply-discipline §4 is right about the hazard: a scripts/sql file that carries DDL must
// not end its self-check with `raise exception`, because the raise takes the `create function` with
// it and the apply reports success over a file that un-built itself. That happened twice. What §4
// prescribed instead was a notice — and a notice prints NOWHERE.
//
// MEASURED 18 Sep 2026, asking the management API directly and reading the raw response body:
//
//     do $$ begin raise notice 'a verdict'; end $$;                  ->  []
//     do $$ begin raise notice 'a verdict'; end $$; select 1 as a;   ->  [{"a":1}]
//     raise warning instead of notice                                ->  [{"a":1}]
//     set client_min_messages to notice; … the same DO block …        ->  [{"a":1}]
//     select name, setting from pg_settings                          ->  log_min_messages = warning
//
// NOTICE and WARNING are both discarded by the API's own driver, `log_min_messages` is 'warning' so a
// notice never reaches the Postgres log either, `psql` is not installed, and no direct connection
// string exists in the environment or in supabase/config.toml. scripts/apply_sql.mjs had no handling
// for messages of any kind — it threw the returned rows away. So the applier has exactly TWO
// channels: a RESULT SET, and an ERROR. §4 forbids the error.
//
// THE POPULATION, measured the same day over 1,123 files in scripts/sql. A count is not a finding
// until you know what you counted, so both numbers are given and the difference is explained:
//     231  raise a notice of any kind                 (most are progress, and losing those is fine)
//      35  raise one whose text is a verdict of FAILURE — the word list below   <- the blind spot
//      28  of those 35 also carry DDL, so §4 forbids them from raising at all
//        6  of those 28 have no `raise exception` anywhere, so a discarded message is their ONLY channel
//      59  under a LOOSER word list that also counts expected / lost / open
//   The 24 files that looser list adds were read one by one and every one of them is a progress or
//   success notice, not a failed verdict — "10 of 10 cases as expected", "% open", "closed: …". So
//   35 is the number this gate measures, and 54 (an earlier pass of the same count, with the looser
//   words and without reading what matched) was an over-count. The register carries the same figure
//   because it is generated by this same detector.
//
// ONE PART OF apply-discipline §4 IS SUPERSEDED BY THIS MEASUREMENT, and the failure message below
// says so, because the skill file is loaded at the start of every session on this repository and
// still prescribes the notice. §4 is right that a DDL file must not raise; it is wrong that a notice
// is the alternative. The alternative is a SELECT verdict.
//
// WHAT THIS ASSERTS: no scripts/sql file may report a FAILED VERDICT through `raise notice`. A file
// carrying DDL reports through its last statement — a SELECT whose value begins with the OK or the
// FAILED marker, which scripts/apply_sql.mjs prints and exits non-zero on. A pure probe file with no
// DDL keeps raising an exception, which is already this estate's pattern. Informational notices are
// not touched: this is about a verdict of failure, not about logging.
//
// THE 35 FILES MEASURED TODAY ARE RECORDED, NOT EXEMPTED. scripts/sql/PROBES_THAT_CANNOT_REPORT.txt
// names each one. They were applied before the convention existed and their notices were lost at the
// time; editing them now would not recover anything, because a probe only runs when its file is
// applied. What matters is that the NEXT one reports, and that the register can only shrink — a
// registered file that has since been fixed is itself a finding, so the list cannot rot into an
// exemption nobody revisits.
//
// This check reads SOURCE ONLY. It never touches the database, so it runs in `npm test` with no
// credential. The patterns it looks for are built from parts below rather than written out as
// sentences, because a check that greps for a string will match the comment that explains it
// (apply-discipline §7) — the words are assembled, never spelled, anywhere above.
import { readdirSync, readFileSync, existsSync } from 'node:fs';
import test from 'node:test';
import assert from 'node:assert/strict';

const SQL_DIR = 'scripts/sql';
const REGISTER = 'scripts/sql/PROBES_THAT_CANNOT_REPORT.txt';

// Assembled, so nothing in this file's own prose can be mistaken for the thing being detected.
const OK_MARKER = ['PROBE', 'OK'].join(' ');
const FAILED_MARKER = ['PROBE', 'FAILED'].join(' ');

/** SQL comments cannot be code. Strip them before looking for anything. */
const stripComments = (t) => t
  .replace(/\/\*[\s\S]*?\*\//g, ' ')
  .split('\n').map((l) => l.replace(/--.*$/, '')).join('\n');

// A notice whose text reads as a verdict of FAILURE rather than as progress. Deliberately wide:
// the cost of a false positive is one converted probe, the cost of a false negative is a verdict
// nobody will ever see.
const VERDICT_WORDS = ['failed', 'fail:', 'violation', 'missing', 'broken', 'not ok', 'mismatch',
  'unexpected', 'did not', 'does not', 'should not', 'no rows', 'cannot', 'could not', 'absent',
  'drift', FAILED_MARKER.toLowerCase()];
const failVerdictNotice = (code) => {
  const re = /raise\s+(?:notice|warning)\s+'([^']*)'/gi;
  for (const m of code.matchAll(re)) {
    const text = m[1].toLowerCase();
    if (VERDICT_WORDS.some((w) => text.includes(w))) return m[1].slice(0, 120);
  }
  return null;
};

const files = readdirSync(SQL_DIR).filter((f) => f.endsWith('.sql'));
const offenders = new Map();       // path -> the offending notice text
for (const f of files) {
  const path = `${SQL_DIR}/${f}`;
  const found = failVerdictNotice(stripComments(readFileSync(path, 'utf8')));
  if (found) offenders.set(path, found);
}

// The register: `path :: why`. A line with no reason is an exclusion nobody explained, which is how
// a register becomes a place to hide a file.
const registered = new Map();
const malformed = [];
if (existsSync(REGISTER)) {
  for (const raw of readFileSync(REGISTER, 'utf8').split(/\r?\n/)) {
    const l = raw.trim();
    if (!l || l.startsWith('#')) continue;
    const i = l.indexOf('::');
    if (i < 0 || !l.slice(i + 2).trim()) { malformed.push(l); continue; }
    registered.set(l.slice(0, i).trim(), l.slice(i + 2).trim());
  }
}

// A CEILING, not a target. The two tests below stop the register pointing at nothing and stop it
// keeping a file that has since been fixed, but NEITHER notices a commit that adds a new offending
// file AND its register line together — that name would be in both sets, so the "no NEW file" test
// below would never see it. The ceiling closes that: the register may shrink freely (which is the
// whole point), and cannot grow without editing this number, which is an edit a reviewer can see and
// has to agree with. Found in review of this change; it was the register's one way to rot.
// 23 Sep 2026 (#896, ceo): raised to 36 for fn_decide_reads_its_prior_outcomes_inline.sql, a live-defect restatement
// whose two warnings are fn_decide's runtime messages, not a probe verdict; see its register line for the debt.
const REGISTER_CEILING_MEASURED_18_SEP_2026 = 36;

test('the register cannot grow: adding a file to it is a decision, not a side effect', () => {
  assert.ok(registered.size <= REGISTER_CEILING_MEASURED_18_SEP_2026,
    `${REGISTER} holds ${registered.size} entries and the ceiling measured on 18 Sep 2026 was `
    + `${REGISTER_CEILING_MEASURED_18_SEP_2026}. It may shrink as files are fixed; it may not grow. `
    + 'A new file reporting a verdict nobody can read is a file to fix, not a line to add. If a line '
    + 'genuinely must be added, raise this ceiling in the same commit so the decision is visible '
    + 'rather than absorbed.');
});

test('a register entry names a real file and a reason', () => {
  assert.deepEqual(malformed, [], `${REGISTER}: every line must read "path :: reason"`);
  const gone = [...registered.keys()].filter((p) => !existsSync(p));
  assert.deepEqual(gone, [], `${REGISTER} points at files that do not exist. An index that points `
    + 'at nothing is worse than no index — remove the line with the file.');
});

test('the register can only shrink: a registered file that now reports must be removed from it', () => {
  const fixed = [...registered.keys()].filter((p) => !offenders.has(p));
  assert.deepEqual(fixed, [], `these files no longer report a failed verdict through a message the `
    + `applier discards, so their lines in ${REGISTER} are stale. Delete them — a register that `
    + 'keeps naming files that were fixed decays into an exemption list nobody reads.');
});

test('no NEW scripts/sql file reports a failed verdict through a message that prints nowhere', () => {
  const news = [...offenders.entries()].filter(([p]) => !registered.has(p));
  const detail = news.map(([p, why]) => `\n  ${p}\n      ${why}`).join('');
  assert.equal(news.length, 0,
    `${news.length} file(s) report a FAILED VERDICT through a message the management API discards, `
    + 'so the verdict prints nowhere and the apply looks clean.'
    + '\n\nNOTE ON apply-discipline §4, which is loaded at the start of every session and which told '
    + 'you to write this: §4 is RIGHT that a file carrying DDL must not `raise exception` from its '
    + 'probe. It is WRONG that a notice is the alternative. Measured 18 Sep 2026: this project\'s '
    + 'management API discards NOTICE and WARNING, log_min_messages is \'warning\' so a notice is not '
    + 'in the Postgres log either, psql is not installed and there is no direct connection string.'
    + `\n\nFix, do not register: make the file's LAST statement a select of one row whose value `
    + `begins "${OK_MARKER}" or "${FAILED_MARKER}". scripts/apply_sql.mjs prints it and exits `
    + 'non-zero on a failure, leaving the applied DDL alone — the change is live and its '
    + 'verification did not pass, which is the honest outcome. A file with NO DDL may instead raise '
    + 'an exception, which rolls back nothing it defined because it defines nothing.'
    + `\n\nWorked example: ${SQL_DIR}/the_export_gate_was_red_because_another_session_held_a_lock.sql`
    + detail);
});

// A PROBE MUST NEVER BE ABLE TO COMMIT (it_engineer, outcome audit 30 Sep 2026). Six *_probe.sql files
// ended their transaction with a bare transaction-end that persists, so a verdict that passed could have
// kept whatever the block wrote outside its own rolled-back sub-block. A probe ends with ROLLBACK.
// The keyword is assembled so this comment cannot match (apply-discipline §7).
test('no *_probe.sql file contains a bare commit', () => {
  const kw = ['com', 'mit'].join('');
  const re = new RegExp(`(^|;)\\s*${kw}\\s*(;|$)`, 'im');
  const bad = files.filter((f) => f.endsWith('_probe.sql'))
    .filter((f) => re.test(stripComments(readFileSync(`${SQL_DIR}/${f}`, 'utf8'))));
  assert.deepEqual(bad, [], `a probe must end in rollback, never ${kw}: ${bad.join(', ')}`);
});

test('the applier actually reads the result set it used to throw away', () => {
  // The convention is worth nothing if apply_sql.mjs stops looking. Anchored on the assignment and
  // on the exit, not on prose, so a comment cannot satisfy it.
  const applier = readFileSync('scripts/apply_sql.mjs', 'utf8');
  // (13 Nov 2026: the apply became a retry loop, `let applied; ... applied = await dbPost(`; still the assignment, never a bare await)
  assert.match(applier, /(?:const )?\bapplied = await dbPost\(/,
    'scripts/apply_sql.mjs must keep the rows the apply returns — `await dbPost(...)` on its own '
    + 'discards the only channel a DDL file has for reporting a verdict.');
  assert.match(applier, /probeFailures\+\+/, 'apply_sql.mjs must count a failed probe verdict.');
  // A PROBE THAT RETURNS NOTHING IS NOT A PASS. An ALTER-only file defines no routine, so the
  // read-back loop never runs and the probe is the file's only verification; a probe matching zero
  // rows then reported nothing and the apply printed success over an unverified change.
  assert.match(applier, /promisesAVerdict && probeVerdicts === 0/,
    'apply_sql.mjs must refuse an apply whose file carries a verdict marker and returns no verdict. '
    + 'Zero rows is not a pass — it is the same blind spot with the message removed instead of '
    + 'discarded.');
  assert.match(applier, /if \(probeFailures\)[\s\S]{0,600}process\.exit\(3\)/,
    'apply_sql.mjs must exit non-zero when a probe verdict reports a failure. Printing it and '
    + 'exiting 0 is the same blind spot with extra steps.');
});
