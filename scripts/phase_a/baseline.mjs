fp.ORGANIZATION = { rows: Object.values(fpSrc).reduce((n, v) => n + v.length, 0),
  sha256: sha(Object.entries(fpSrc).map(([k, v]) => `${k}\n${v.join('\n')}`).join('\n--\n')) };

say('### Pre-change organization fingerprint');
