// ---- reporting graph ----------------------------------------------------------------------------
// Acyclicity is checked on the PACKAGE graph (it is the target) and on the LIVE graph separately.
function cycles(edges) {
  const mgr = new Map(edges.map(e => [e.child, e.parent]));
  const bad = [];
  for (const start of mgr.keys()) {
    const seen = new Set([start]);
    let cur = mgr.get(start);
    while (cur && mgr.has(cur)) {
      if (seen.has(cur)) { bad.push(`${start} -> … -> ${cur}`); break; }
      seen.add(cur); cur = mgr.get(cur);
    }
  }
  return bad;
}
const pkgCycles = cycles(T.graph.map(g => ({ child: g.role_id, parent: g.manager_role_id })));
const liveCycles = cycles(accountable.filter(r => r.manager_role_id)
  .map(r => ({ child: r.role_id, parent: r.manager_role_id })));
