// ---- crosswalk ----------------------------------------------------------------------------------
// Every package role matched to a live role by canonical id, then by legacy alias, then by title.
const liveById = new Map(live.roles.map(r => [r.role_id.toLowerCase(), r]));
const liveByTitle = new Map();
for (const r of live.roles) {
  const k = norm(r.display_name);
  if (!liveByTitle.has(k)) liveByTitle.set(k, r);
}
const cross = [];
for (const t of T.roles) {
  const aliases = String(t.legacy_aliases || '').split(/[;,]/).map(s => s.trim()).filter(Boolean);
  let hit = liveById.get(t.canonical_role_id.toLowerCase()) || null, how = hit ? 'canonical id' : null;
  if (!hit) for (const a of aliases) {
    const h = liveById.get(a.toLowerCase());
    if (h) { hit = h; how = `legacy alias ${a}`; break; }
  }
  if (!hit) { const h = liveByTitle.get(norm(t.display_title)); if (h) { hit = h; how = 'display title'; } }
  cross.push({ target: t.canonical_role_id, title: t.display_title, dept: t.department_id,
    action: t.change_action, live: hit ? hit.role_id : null, how: how || 'UNMATCHED' });
}
const unmatched = cross.filter(c => !c.live);
const byId = cross.filter(c => c.how === 'canonical id').length;

say('### Crosswalk — package role → live role');
say('');
say(`Matched by canonical id: **${byId}** · by legacy alias: **${cross.filter(c => c.how.startsWith('legacy')).length}** · `
  + `by display title: **${cross.filter(c => c.how === 'display title').length}** · unmatched: **${unmatched.length}**`);
say('');
if (unmatched.length) {
  say('| package role | title | package department | change_action |');
  say('|---|---|---|---|');
  for (const c of unmatched) say(`| \`${c.target}\` | ${c.title} | \`${c.dept}\` | ${c.action} |`);
  say('');
}

