// ---- CSV ---------------------------------------------------------------------------------------
// Quoted fields carry commas and semicolons throughout these registries, so a split(',') would
// silently mis-column 90 roles. This walks the text once and tracks whether a quote is open.
function parseCsv(text) {
  const rows = [];
  let row = [], field = '', q = false;
  const s = text.replace(/^﻿/, '').replace(/\r\n/g, '\n');
  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if (q) {
      if (c === '"') { if (s[i + 1] === '"') { field += '"'; i++; } else q = false; }
      else field += c;
    } else if (c === '"') q = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
    else field += c;
  }
  if (field.length || row.length) { row.push(field); rows.push(row); }
  const head = rows.shift().map(h => h.trim());
  return rows.filter(r => r.some(v => String(v).trim()))
    .map(r => Object.fromEntries(head.map((h, i) => [h, String(r[i] ?? '').trim()])));
}
