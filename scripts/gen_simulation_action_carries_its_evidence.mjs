// Generate scripts/sql/simulation_action_carries_its_evidence.sql — the approval a simulation
// creates cites the simulation, rather than falling back to a generic stamped line.
//
// fn_governance_stamp now stamps a generic evidence basis for any row that arrives without one
// ("deterministic rule from live platform data"), which is the right safety net and the wrong
// description here: this action does not rest on a deterministic rule, it rests on simulation #N and
// the figures that simulation actually computed. Naming the real basis is strictly better than
// accepting a default that describes something else.
//
//   node scripts/gen_simulation_action_carries_its_evidence.mjs
//   node scripts/apply_sql.mjs scripts/sql/simulation_action_carries_its_evidence.sql --promote
import { writeFileSync } from 'node:fs';
import { mgmtRead, PROD_REF } from './lib/qd_guard.mjs';

const ANCHOR = `                              target_table, target_id, confidence)`;
const REPL = `                              target_table, target_id, confidence, evidence)`;

const ANCHOR2 = `            'simulations', v_id::text, v_conf);`;
const REPL2 = `            'simulations', v_id::text, v_conf,
            -- The real basis, not the generic stamped one: this rests on the simulation and the
            -- figures it computed, which are the two things a reader would want to check.
            jsonb_build_object('basis', 'simulation #' || v_id || ' of "' || p_question || '"',
                               'simulation_id', v_id, 'confidence', v_conf, 'projection', v_impact));`;

const rows = await mgmtRead(
  PROD_REF,
  `select pg_get_functiondef(p.oid) as def from pg_proc p join pg_namespace n on n.oid=p.pronamespace
    where n.nspname='public' and p.proname='fn_what_if'`,
);
const def = rows?.[0]?.def;
if (!def) { console.error('fn_what_if not found'); process.exit(1); }
if (/confidence, evidence\)/.test(def)) { console.log('SKIP already cites its evidence'); process.exit(0); }
for (const [a, n] of [[ANCHOR, 'column list'], [ANCHOR2, 'values list']]) {
  const hits = def.split(a).length - 1;
  if (hits !== 1) { console.error(`ANCHOR (${n}) found ${hits} time(s), expected exactly 1 — refusing`); process.exit(1); }
}

writeFileSync(
  'scripts/sql/simulation_action_carries_its_evidence.sql',
  [
    `-- GENERATED by scripts/gen_simulation_action_carries_its_evidence.mjs — do not hand-edit.`,
    `--`,
    `-- The approval a simulation creates now cites the simulation and the figures it computed,`,
    `-- instead of falling through to fn_governance_stamp's generic "deterministic rule from live`,
    `-- platform data", which describes a different kind of action entirely.`,
    ``,
    def.replace(ANCHOR, REPL).replace(ANCHOR2, REPL2).trimEnd() + ';',
    ``,
  ].join('\n'),
);
console.log('OK   fn_what_if action now cites its simulation\nwrote scripts/sql/simulation_action_carries_its_evidence.sql');
