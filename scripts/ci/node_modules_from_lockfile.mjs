// A LOCKFILE-EXACT node_modules WITHOUT A SECOND 2 GB INSTALL (it_engineer, 11 Nov 2026).
//
// Why it exists. The cloud session had 750 MB free and `npm ci` needs about 2 GB, and the shared tree every gate
// links to is NOT the lockfile: the gate's own `deno ... --node-modules-dir=auto` steps rewrite it into Deno's layout
// (`node_modules/.deno/<name>@<version>/`), which resolves `^` ranges afresh and ignores npm `overrides`. Measured
// 11 Nov 2026: 13 of 215 top-level packages differed from package-lock.json, and sharp was 0.34.5 although the
// override pins ^0.35.5 for GHSA-wq5f-xc86-pv6w (docs/engineering/tech-debt.md TD-24). So a Dependabot PR could not
// be tested on the tree it would actually ship.
//
// What it does. For every entry of a lockfile's `packages` map it hard-links (cp -al) the package's own files out of
// an existing Deno store when that store holds the exact version, and otherwise downloads the entry's `resolved`
// tarball, checks it against the lockfile's sha512 `integrity`, and extracts it. Entries for another os/cpu/libc are
// skipped as npm would skip them (this targets linux-x64-glibc). Hard links cost inodes, not bytes: building the
// whole tree took ~0 MB of disk plus the packages the store lacked (35 for main's lockfile).
//
// Rules it keeps. It never writes into the store, and it refuses an existing output directory. Because the files
// are hard links, nothing may modify them in place: do not run `deno --node-modules-dir=auto` or `npm install` in a
// tree built this way; delete it (`rm -rf` only unlinks) and rebuild instead.
//
// Turbopack refuses a node_modules whose real path is outside the project, so build it INSIDE the worktree:
//   rm node_modules   # the link to the shared tree
//   NODE_USE_ENV_PROXY=1 node scripts/ci/node_modules_from_lockfile.mjs package-lock.json /tmp/claude-0/gate-1876/node_modules ./node_modules
//   npx tsc --noEmit && npx oxlint && npx next build
//   rm -rf node_modules && ln -s /tmp/claude-0/gate-1876/node_modules node_modules
// If disk is short for `next build` (~400 MB of output), link .next to tmpfs and set NODE_PATH=$PWD/node_modules so the
// PostCSS worker, which runs from the build directory, still finds the project's packages.
//
// usage: node scripts/ci/node_modules_from_lockfile.mjs <package-lock.json> <store node_modules> <out node_modules>
import fs from 'node:fs'; import path from 'node:path'; import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
// Which entries npm would install here is one function, shared with the gate's node-tree step
// (scripts/lib/lockfile_tree.mjs), so the tree this builds and the check that certifies it cannot disagree.
import { lockEntries } from '../lib/lockfile_tree.mjs';
const [lockFile, store, out] = process.argv.slice(2);
if (fs.existsSync(out)) throw new Error(`${out} exists; refusing to reuse it`);
const lock = JSON.parse(fs.readFileSync(lockFile, 'utf8'));
let linked = 0, fetched = 0; const bins = [];
fs.mkdirSync(out, { recursive: true });
const entries = lockEntries(lock);
const skipped = Object.keys(lock.packages).filter((k) => k.startsWith('node_modules/')).length - entries.length;
for (const { key: k, name, entry: v } of entries) {
  const dest = path.join(out, k.slice('node_modules/'.length));
  const src = path.join(store, '.deno', `${name.replace('/', '+')}@${v.version}`, 'node_modules', name);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  if (fs.existsSync(path.join(src, 'package.json'))) {
    fs.mkdirSync(dest, { recursive: true });
    // copy the package's own files, not its nested node_modules (npm nests those as their own lock entries)
    for (const f of fs.readdirSync(src)) if (f !== 'node_modules') execFileSync('cp', ['-al', path.join(src, f), dest]);
    linked++;
  } else {
    if (!v.resolved) throw new Error(`no resolved url for ${k}`);
    const res = await fetch(v.resolved, { signal: AbortSignal.timeout(120_000) }); if (!res.ok) throw new Error(`${res.status} ${v.resolved}`);
    const buf = Buffer.from(await res.arrayBuffer());
    const [alg, want] = v.integrity.split('-');
    const got = crypto.createHash(alg).update(buf).digest('base64');
    if (got !== want) throw new Error(`integrity mismatch for ${k}`);
    fs.mkdirSync(dest, { recursive: true });
    execFileSync('tar', ['-xzf', '-', '-C', dest, '--strip-components=1', '--no-same-owner'], { input: buf });
    fetched++; console.log(`fetched ${k}@${v.version} (${(buf.length / 1e6).toFixed(1)} MB)`);
  }
  if (v.bin && !k.slice('node_modules/'.length).includes('node_modules/')) for (const [b, rel] of Object.entries(v.bin)) bins.push([b, path.join('..', k.slice('node_modules/'.length), rel)]);
}
fs.mkdirSync(path.join(out, '.bin'), { recursive: true });
for (const [b, rel] of bins) { const p = path.join(out, '.bin', b); if (!fs.existsSync(p)) fs.symlinkSync(rel, p); }
console.log(`linked ${linked}, fetched ${fetched}, skipped ${skipped}, bins ${bins.length}`);
