// Generate scripts/sql/simulation_offers_the_action.sql — a simulation that produced a real
// projection now leaves an approval the founder can act on, referencing the simulation itself.
//
// MEASURED, production 11 Aug 2026: `what-if-approve-from-simulation` reads
//   ui: 1 approve control(s) bound to a simulation, 2 simulation action(s) in os_api
//   db: 0 approval row(s) reference a simulation, of 1337 agent actions
// The screen half already passes. Nothing has ever created the action, so there is nothing to
// approve from — the founder can see a projection and has no way to act on it without leaving it.
//
// THE CONFIDENCE FLOOR IS THE HONESTY GATE, and it is the simulator's own number, not a new one.
// fn_what_if scores each branch as it answers: 0.2 when there is no model for the question at all
// ("Add a scenario to scenario_library so it can be simulated rather than guessed"), 0.45 on the
// invite branch whose own text says it rests on "an assumption not an observation", and 0.7 where it
// has real counts behind it. Offering an approval only at >= 0.5 means the branches the simulator
// itself flags as weakly grounded produce no action — which is the difference between a decision
// support tool and a suggestion box.
//
// It does not page. fn_page_high_agent_action fires only for risk in (high, critical) AND agent in
// (finance_ai, security_ai, operations_ai); this writes medium risk from strategy_director, an
// active exec employee that holds an employee_authority row, so it lands in the queue and waits.
//
// Generated rather than hand-written for the same reason as the surfaces: fn_what_if is 7.5k
// characters of branch logic and the change is one inserted block. The body is read back from the
// live database and one anchored string is replaced; the script refuses if the anchor is not found
// exactly once.
//
//   node scripts/gen_simulation_offers_the_action.mjs
//   node scripts/apply_sql.mjs scripts/sql/simulation_offers_the_action.sql --promote
import { writeFileSync } from 'node:fs';
import { mgmtRead, PROD_REF } from './staging/qd_guard.mjs';

const ANCHOR = `  returning id into v_id;`;

const BLOCK = `  returning id into v_id;

  -- THE SIMULATION LEAVES SOMETHING TO APPROVE. Only when it actually modelled the question:
  -- v_conf is the simulator's own score for the branch it took, and below 0.5 are exactly the
  -- branches whose text says they are guesses ("No model exists for this question yet",
  -- "an assumption not an observation"). Those produce a projection to read and no action to take.
  if v_conf >= 0.5 then
    insert into agent_actions(agent, kind, status, risk, title, recommendation, detail,
                              target_table, target_id, confidence)
    values ('strategy_director', 'simulation_apply', 'pending', 'medium',
            left('Act on the simulation: ' || p_question, 200),
            coalesce(v_impact->>'assessment',
                     'The simulation returned a projection; open it to see the modelled figures.')
              || ' Approving this accepts the modelled change; the projection and its basis are on '
              || 'simulation #' || v_id || '.',
            jsonb_build_object('simulation_id', v_id, 'question', p_question,
                               'change', p_change, 'projection', v_impact),
            'simulations', v_id::text, v_conf);
  end if;`;

const rows = await mgmtRead(
  PROD_REF,
  `select pg_get_functiondef(p.oid) as def from pg_proc p join pg_namespace n on n.oid=p.pronamespace
    where n.nspname='public' and p.proname='fn_what_if'`,
);
const def = rows?.[0]?.def;
if (!def) { console.error('fn_what_if not found'); process.exit(1); }
if (/simulation_apply/.test(def)) { console.log('SKIP fn_what_if already offers the action'); process.exit(0); }
const hits = def.split(ANCHOR).length - 1;
if (hits !== 1) { console.error(`ANCHOR found ${hits} time(s), expected exactly 1 — refusing`); process.exit(1); }

writeFileSync(
  'scripts/sql/simulation_offers_the_action.sql',
  [
    `-- GENERATED by scripts/gen_simulation_offers_the_action.mjs — do not hand-edit.`,
    `--`,
    `-- fn_what_if now leaves an approval the founder can act on when, and only when, it actually`,
    `-- modelled the question (its own confidence >= 0.5). The action references the simulation by`,
    `-- target_table='simulations' / target_id, which is what the screen's approve control binds to.`,
    ``,
    def.replace(ANCHOR, BLOCK).trimEnd() + ';',
    ``,
  ].join('\n'),
);
console.log('OK   fn_what_if (+1 conditional block)\nwrote scripts/sql/simulation_offers_the_action.sql');
