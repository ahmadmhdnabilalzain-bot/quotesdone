// READER B — make fn_ws_customer_360 REMEMBER a customer's preferences instead of re-deriving them.
//
// This generates the new definition by ONE EXACT STRING REPLACEMENT against the LIVE
// pg_get_functiondef output, and refuses unless the anchor matches exactly once. It is written this
// way on purpose:
//
//  - supabase/schema/full_schema.sql is demonstrably stale (it still carries the pre-session
//    fn_agent_institutional_memory), so editing from the dump would silently revert whatever else
//    has changed in the deployed body.
//  - A DO block that rewrites pg_get_functiondef in place reports success even when the result
//    cannot run — that is exactly how three call-time bugs shipped green in session 12. Here the
//    result is written to a .sql file, applied through the normal path, and then exercised by a
//    fixture that actually calls the function.
//  - The function is 5,251 characters. Retyping it is the bug class promote_rows_to_production
//    exists to prevent.
//
//   node scripts/gen_customer_360_reader.mjs      # writes scripts/sql/fn_ws_customer_360.sql
import { writeFileSync } from 'node:fs';
import { mgmtRead, PROD_REF } from './staging/qd_guard.mjs';

const live = (await mgmtRead(PROD_REF,
  `select pg_get_functiondef(p.oid) d from pg_proc p
     join pg_namespace ns on ns.oid = p.pronamespace
    where ns.nspname='public' and p.proname='fn_ws_customer_360'`))[0].d;

// The exact block being replaced, as it stands in the deployed function.
const ANCHOR = `    'preferences', jsonb_build_object(
       'categories', coalesce((select jsonb_agg(distinct category) from public.inquiries where customer_id=p_id and category is not null),'[]'::jsonb),
       'emirates', coalesce((select jsonb_agg(distinct emirate) from public.inquiries where customer_id=p_id and emirate is not null),'[]'::jsonb)),`;

// The same two key names are kept so no consumer's contract changes — os_api's ws.customer action
// and fn_query_platform's customer_360 branch, which secretary_act exposes as a tool topic.
// `remembered` is added so a reader can tell a recalled preference from a re-derived one, and the
// live derivation stays as the fallback for a customer who has not consented.
const REPLACEMENT = `    'preferences', (
       with pref as (select p.preferences pj from public.customer_preference p
                       join public.customers cc on cc.id = p.customer_id
                      where p.customer_id = p_id and cc.tos_accepted_at is not null)
       select jsonb_build_object(
         'categories', coalesce((select pj->'stated'->'categories' from pref),
                                (select pj->'inferred'->'categories' from pref),
                                coalesce((select jsonb_agg(distinct category) from public.inquiries where customer_id=p_id and category is not null),'[]'::jsonb)),
         'emirates',   coalesce((select pj->'stated'->'emirates' from pref),
                                (select pj->'inferred'->'emirates' from pref),
                                coalesce((select jsonb_agg(distinct emirate) from public.inquiries where customer_id=p_id and emirate is not null),'[]'::jsonb)),
         'scope_type', (select pj->'inferred'->>'scope_type' from pref),
         'budget_aed_avg', (select pj->'inferred'->'budget_aed_avg' from pref),
         'remembered', exists(select 1 from pref))),`;

const hits = live.split(ANCHOR).length - 1;
if (hits !== 1) {
  console.error(`REFUSED: the anchor matched ${hits} time(s), expected exactly 1.`);
  console.error('The deployed fn_ws_customer_360 is not what this generator was written against.');
  console.error('Re-read it with pg_get_functiondef and update ANCHOR before running again.');
  process.exit(1);
}

const out = live.replace(ANCHOR, REPLACEMENT) + ';\n';
const header = `-- GENERATED by scripts/gen_customer_360_reader.mjs from the LIVE production definition.
-- Do not hand-edit: regenerate. One exact-match replacement of the 'preferences' block, which
-- re-derived a customer's categories and emirates from their inquiry history on every call.
-- customer_preference is now consulted first (stated over inferred), with the old live derivation
-- kept as the fallback for a customer who has not consented — so behaviour for them is unchanged.
`;
writeFileSync('scripts/sql/fn_ws_customer_360.sql', header + out, 'utf8');
console.log(`written scripts/sql/fn_ws_customer_360.sql — ${live.length} -> ${out.length} chars`);
