do $proof$
declare v text; v_n int;
begin
  select content into v from public.ops_knowledge where record_id = 'qd-company:registration';
  if v is null then raise exception 'qd-company:registration was not written'; end if;
  if position('1633275' in v) = 0 or position('375,000' in v) = 0 or position('24 Jun 2027' in v) = 0 then
    raise exception 'registration record is missing the licence number, the VAT threshold or the expiry';
  end if;
  select count(*) into v_n from public.company_registration where license_no = '1633275';
  if v_n <> 1 then raise exception 'expected one registration row, got %', v_n; end if;
  raise notice 'proof: qd-company:registration carries licence 1633275, expiry 24 Jun 2027 and the AED 375,000 VAT threshold';
end $proof$;

