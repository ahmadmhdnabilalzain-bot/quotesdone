--     NOT EMBEDDED  regulation    0 / 45      no semantic path to any of these rows
--     NOT EMBEDDED  material      0 / 3       no semantic path to any of these rows
--
-- kb_embed already knows how to fix this. On 11 Aug an optional `source_kinds` filter was added to
-- it for precisely these rows, and the comment beside it says why in full: they arrived after the
-- 115,148-row pack import, strict FIFO leaves UAE regulations and trade knowledge ~56 hours behind
-- a queue of pack chunks, and "those are exactly the rows an employee is most likely to be wrong
-- about without". The design was deliberate - an optional filter rather than a hard-coded priority,
-- so the fair FIFO keeps running and "a second caller can drain a named, FINITE set first".
--
-- THAT SECOND CALLER WAS NEVER CREATED. Both kb_embed cron jobs - kb_embed_backfill and
-- kb_embed_backfill_boost - post the default body with no source_kinds, so the filter has never
-- once been exercised and the three kinds sit at exactly 0%, one day later, as predicted. Nothing
-- failed; there was simply nothing to ask for them. Sixth instance this week of a finished,
-- hardened capability with no entry point.
--
-- This is the caller. It is deliberately a THIRD job rather than a change to either existing one:
-- the note is explicit that the default must stay unchanged so the pack corpus is not starved.
--
-- It is self-limiting. The set is finite (2,090 rows across both projects' equivalents); at 5 rows
-- x 6 posts a minute it drains in roughly an hour, after which kb_embed finds nothing matching and
-- the job costs one no-op HTTP call a minute. Embedding is the free in-region gte-small model, so
-- there is no bill attached to it either way. The batch stays at 5 - the measured ceiling on this
-- project's edge worker, where 8 returns HTTP 546 - and throughput comes from invocation count,
-- never from batch size.

