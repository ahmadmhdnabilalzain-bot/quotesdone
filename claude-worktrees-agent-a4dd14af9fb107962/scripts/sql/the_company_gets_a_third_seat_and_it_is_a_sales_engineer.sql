-- 7. THE SCOPED CREDENTIAL. Same shape as every other cred_* entry.
do $mint$
declare v_secret text;
begin
  if exists (select 1 from public.internal_credential where context = 'fn.sales_engineer') then
    raise notice 'fn.sales_engineer already exists -- left untouched';
    return;
  end if;

  v_secret := encode(extensions.gen_random_bytes(32), 'hex');

  insert into public.internal_credential (context, label, secret_hash, scope, is_legacy, active)
  values (
    'fn.sales_engineer',
    'The Sales Engineer seat -- inquiry intake, supplier verification, matching and safe dispatch',
    public.fn_internal_credential_hash(v_secret),
    array['sales_engineer'],
    false,
    true
  );

  insert into public.app_secrets (key, value)
  values ('cred_fn_sales_engineer', v_secret)
  on conflict (key) do update set value = excluded.value;
end
$mint$;

