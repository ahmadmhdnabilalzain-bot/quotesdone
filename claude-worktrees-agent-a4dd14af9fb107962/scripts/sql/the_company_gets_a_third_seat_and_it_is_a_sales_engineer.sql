-- THE COMPANY GETS A THIRD SEAT, AND IT IS A SALES ENGINEER.
--
-- The founder, 9 Sep 2026: "I deleted the old organization and am rebuilding it one agent at a time.
-- The new CEO was first, Customer Support second, and this single Sales Engineer is third. Sales
-- Engineer and Customer Support report directly to the actual new CEO."
--
-- This file makes the seat EXIST as an authenticated actor. It does not give it a runtime, a model,
-- or any capability -- those follow in their own files. Everything here was measured first, because
-- five separate structures refuse a third agent today and each refuses for a different reason.
--
-- WHAT WAS MEASURED, 9 Sep 2026:
--   org_agents            2 rows (ceo, customer_support), department and manager_key NULL on both
--   org_role              2 rows -- and ceo_standing_grant.grantee_role_id is an FK to it, so a
--                         grant is STRUCTURALLY IMPOSSIBLE without a role row
--   org_reporting_edge    1 row (customer_support -> ceo). fn_support_report_to_ceo resolves its
--                         recipient through this table and REFUSES rather than inventing one, so a
--                         seat with no edge cannot report at all
--   function_owner_owner_ck   CHECK (owner = ANY (ARRAY['ceo','customer_support','website']))
--                         -- a live constraint; the seat cannot own an edge function until it admits
--                         sales_engineer
--   fn_support_may_act    grantee_role_id is HARD-CODED to 'customer_support'
--
-- WHY fn_agent_may_act RATHER THAN fn_sales_may_act. The obvious move is to copy the support
-- routine and change the literal. That would give the company two copies of its authority rule, and
-- the next seat a third. The grantee becomes a parameter; fn_support_may_act keeps its signature and
-- delegates, so its four existing callers -- fn_support_deliver_artifact, fn_support_receive_document,
-- fn_support_investigate_refund, fn_support_open_identity_challenge -- are untouched and keep
-- behaving identically. The refusal text, the expiry check and the amount ceiling are preserved
-- exactly, including the sentence that says an uncovered action is a CEO decision and not a founder
-- approval.
--
-- THE GRANTS ARE NARROW ON PURPOSE. The integration document asks for "narrow standing grants for
-- routine intake, existing-scope validation, matching, safe dispatch and compliant invitations".
-- Five action classes, one grant each, so a compromise or a mistake in one does not carry the others.
-- sales.invitation is issued INACTIVE and says why in its own scope_note: the acquisition list is
-- 22,264 scraped rows with no consent column in the table, and the configured provider prohibits
-- cold outreach. A grant that cannot be exercised lawfully is not issued as if it could be.
--
-- THE CREDENTIAL VALUE NEVER LEAVES THE DATABASE. Generated by gen_random_bytes, hashed by
-- fn_internal_credential_hash, plaintext written to app_secrets under the key the callers read. It
-- is not in this file, not in the repository, and was never in a chat window. Idempotent by
-- existence check, not by regeneration -- re-applying must never mint a second secret and leave the
-- callers holding the first.
--
--   node scripts/apply_sql.mjs scripts/sql/the_company_gets_a_third_seat_and_it_is_a_sales_engineer.sql --apply --ddl

