-- 9. THE CLOSING ASSERTION. A file that was supposed to seat an agent and did not must say so.
do $check$
declare
  v_agent int; v_role int; v_edge int; v_grants int; v_cred int; v_owner int; v_delegates boolean;
begin
  select count(*) into v_agent  from public.org_agents where agent_key = 'sales_engineer' and active;
  select count(*) into v_role   from public.org_role   where role_id   = 'sales_engineer';
  select count(*) into v_edge   from public.org_reporting_edge
    where child_role_id = 'sales_engineer' and parent_role_id = 'ceo';
  select count(*) into v_grants from public.ceo_standing_grant where grantee_role_id = 'sales_engineer';
  select count(*) into v_cred   from public.internal_credential
    where context = 'fn.sales_engineer' and active and 'sales_engineer' = any(scope);
  select count(*) into v_owner  from public.function_owner where function_slug = 'sales_engineer';

  -- The delegation must actually work, not merely compile.
  select (public.fn_support_may_act('conversation') ->> 'may_act')::boolean into v_delegates;

  if v_agent <> 1 or v_role <> 1 or v_edge <> 1 or v_grants <> 5 or v_cred <> 1 or v_owner <> 1 then
    raise exception 'SEAT NOT ESTABLISHED: agent=% role=% edge=% grants=% cred=% owner=%',
      v_agent, v_role, v_edge, v_grants, v_cred, v_owner;
  end if;

  if v_delegates is distinct from true then
    raise exception 'DELEGATION BROKE SUPPORT: fn_support_may_act(''conversation'') returned % -- it must still be true, support.reply is an active grant', v_delegates;
  end if;

  raise notice 'sales_engineer seated: 1 agent, 1 role, 1 reporting edge, 5 grants (4 active + invitation held), 1 credential, 1 function owner; fn_support_may_act still true through delegation';
end
$check$;

