-- v_department_health — every department now has a health measure, not ten of fifteen.
--
-- The view was a hard-coded union of ten departments. Intelligence, Knowledge Engineering,
-- Evolution, Supplier Success and Data & Analytics had NO health value at all, so both
-- digital-twin-department-health and ai-conversation-which-dept-needs-help failed on coverage —
-- and, more to the point, the founder asking "which department needs help?" was being answered
-- wrongly for five of them rather than not at all.
--
-- EACH NEW MEASURE IS A REAL RATIO OVER A REAL TABLE, and the basis column says exactly what it
-- counts. Evolution scores low because 31 of its 32 proposals are genuinely undecided; that is the
-- measurement working, not a defect in it.
--
-- Generated by reading the deployed view definition back and inserting five branches, so the ten
-- that already worked are byte-identical.
--   node scripts/apply_sql.mjs scripts/sql/v_department_health.sql --ddl
create or replace view public.v_department_health as
 WITH dept_scores AS (
         SELECT 'it'::text AS dept_key,
            'Technology'::text AS department,
            round(((( SELECT COALESCE(100.0 * count(*) FILTER (WHERE health_checks.ok)::numeric / NULLIF(count(*), 0)::numeric, 0::numeric) AS "coalesce"
                   FROM health_checks
                  WHERE health_checks.created_at > (now() - '24:00:00'::interval))) + (( SELECT COALESCE(100.0 * count(*) FILTER (WHERE agent_runs.status = 'ok'::text)::numeric / NULLIF(count(*), 0)::numeric, 0::numeric) AS "coalesce"
                   FROM agent_runs
                  WHERE agent_runs.started_at > (now() - '24:00:00'::interval)))) / 2::numeric) AS score,
            'uptime + agent success rate, last 24h'::text AS basis
        UNION ALL
         SELECT 'knowledge'::text,
            'Operations'::text,
            ( SELECT COALESCE(round(avg(v_test_matrix.pass_pct)), 0::numeric) AS "coalesce"
                   FROM v_test_matrix) AS "coalesce",
            'average pass rate across all test suites, 14d'::text
        UNION ALL
         SELECT 'procurement'::text,
            'Marketplace & Procurement'::text,
            ( SELECT round(100.0 * count(*) FILTER (WHERE category_agent_map.status = 'mapped'::text)::numeric / NULLIF(count(*), 0)::numeric) AS round
                   FROM category_agent_map) AS round,
            'supplier categories covered of 84'::text
        UNION ALL
         SELECT 'marketing'::text,
            'Marketing'::text,
            ( SELECT COALESCE(round(100.0 * count(*) FILTER (WHERE review_chain.decision = 'approve'::text)::numeric / NULLIF(count(*), 0)::numeric), 100::numeric) AS "coalesce"
                   FROM review_chain
                  WHERE review_chain.stage = 'dept_review'::text) AS "coalesce",
            'share of drafts approved at first department review'::text
        UNION ALL
         SELECT 'legal'::text,
            'Legal & Compliance'::text,
            ( SELECT
                        CASE
                            WHEN count(*) = 0 THEN 100::bigint
                            ELSE GREATEST(0::bigint, 100 - count(*) * 20)
                        END AS "greatest"
                   FROM risk_register
                  WHERE risk_register.dept_key = 'legal'::text AND risk_register.status = 'open'::text AND risk_register.impact = 'high'::text) AS "greatest",
            'open high-impact legal risks (target zero)'::text
        UNION ALL
         SELECT 'finance'::text,
            'Finance'::text,
            ( SELECT COALESCE(round(100.0 * count(*) FILTER (WHERE agent_runs.status = 'ok'::text)::numeric / NULLIF(count(*), 0)::numeric), 0::numeric) AS "coalesce"
                   FROM agent_runs
                  WHERE agent_runs.agent = 'money_tests'::text AND agent_runs.started_at > (now() - '14 days'::interval)) AS "coalesce",
            'money invariant test pass rate, 14d'::text
        UNION ALL
         SELECT 'exec'::text,
            'Executive Office'::text,
            ( SELECT round(100.0 * count(*) FILTER (WHERE v_employee_knowledge_compliance.kpis > 0 AND v_employee_knowledge_compliance.authorities > 0)::numeric / NULLIF(count(*), 0)::numeric) AS round
                   FROM v_employee_knowledge_compliance) AS round,
            'employees with both a KPI and defined authority'::text
        UNION ALL
         SELECT 'hr'::text,
            'Human Resources'::text,
            ( SELECT round(100.0 * avg(v_employee_knowledge_compliance.layers_bound) / 12::numeric) AS round
                   FROM v_employee_knowledge_compliance) AS round,
            'average employee knowledge layers bound of 12'::text
        UNION ALL
         SELECT 'customer_success'::text,
            'Customer Success'::text,
            0,
            'no customers, inquiries or quotes exist yet - unmeasurable'::text
        UNION ALL
         SELECT 'sales'::text,
            'Sales & Growth'::text,
            0,
            'no transactions exist yet - unmeasurable'::text
        UNION ALL
         SELECT 'intelligence'::text,
            'Intelligence'::text,
            ( SELECT COALESCE(round(100.0 * count(*) FILTER (WHERE company_goals.measure_sql IS NOT NULL)::numeric / NULLIF(count(*), 0)::numeric), 0::numeric)
                   FROM company_goals WHERE company_goals.active),
            'share of active company goals that carry a measurable definition'::text
        UNION ALL
         SELECT 'knowledge_eng'::text,
            'Knowledge Engineering'::text,
            ( SELECT COALESCE(round(100.0 * count(*) FILTER (WHERE agent_knowledge.review_due IS NULL OR agent_knowledge.review_due > now())::numeric / NULLIF(count(*), 0)::numeric), 0::numeric)
                   FROM agent_knowledge),
            'share of knowledge items still inside their review window'::text
        UNION ALL
         SELECT 'evolution'::text,
            'Evolution'::text,
            ( SELECT COALESCE(round(100.0 * count(*) FILTER (WHERE evolution_proposal.status <> 'proposed')::numeric / NULLIF(count(*), 0)::numeric), 0::numeric)
                   FROM evolution_proposal WHERE evolution_proposal.created_at > (now() - '180 days'::interval)),
            'share of structural proposals that have been decided, 180d'::text
        UNION ALL
         SELECT 'supplier_success'::text,
            'Supplier Success'::text,
            ( SELECT COALESCE(round(100.0 * count(*) FILTER (WHERE leads.approval_status = 'approved')::numeric / NULLIF(count(*) FILTER (WHERE leads.registration_submitted_at IS NOT NULL), 0)::numeric), 0::numeric)
                   FROM leads),
            'share of submitted supplier registrations that reached approved'::text
        UNION ALL
         SELECT 'analytics'::text,
            'Data & Analytics'::text,
            ( SELECT COALESCE(round(100.0 * count(*) FILTER (WHERE company_index.measured_on > (CURRENT_DATE - 2))::numeric / NULLIF(count(DISTINCT company_index.index_name), 0)::numeric), 0::numeric)
                   FROM company_index),
            'share of company indices measured in the last two days'::text
        )
 SELECT dept_key,
    department,
    GREATEST(0::numeric, LEAST(100::numeric, COALESCE(score, 0::numeric))) AS score,
    basis,
        CASE
            WHEN COALESCE(score, 0::numeric) >= 90::numeric THEN 'healthy'::text
            WHEN COALESCE(score, 0::numeric) >= 70::numeric THEN 'watch'::text
            WHEN COALESCE(score, 0::numeric) > 0::numeric THEN 'at risk'::text
            ELSE 'no data'::text
        END AS status
   FROM dept_scores;;
