--
-- THE DEFECT, MEASURED. public.org_agents holds five rows — accountant, ceo, customer_support,
-- it_engineer, sales_engineer — and public.org_tasks.assigned_agent carries
-- org_tasks_assigned_agent_fkey REFERENCES org_agents(agent_key). The live body of
-- fn_supplier_sanctions_screen opened its two tasks on 'compliance_mgr' and 'bd', which were seats of
-- the organisation chart the founder removed on 7 Sep 2026. So the routine does not degrade on its
-- first real sanctions hit — it raises
--     23503  Key (assigned_agent)=(compliance_mgr) is not present in table "org_agents"
-- and the whole screening run rolls back: no hit recorded, no task opened, nobody told. The only
-- reason nobody has seen it is that it has never matched anybody: production holds 0 screening_run,
-- 0 screening_entry and 0 supplier_screening_hit rows, so the loop that fetches the lists has never
-- produced a match to open a task for. This is the estate's "a guard that names a remedy that does
-- not exist" shape — the screen runs, finds nothing, and looks healthy.
--
-- WHY THESE TWO SEATS, AND NOT THE OTHER WAY ROUND. The routine opens two tasks that do different
-- work, and each one goes to the seat that does that work:
--   * the DECISION task — "compare the licence, owner and address against the listing and decide
--     confirmed | false_positive" — goes to the ceo. A confirmed decision BANS the supplier
--     (leads.banned, matching_blocked, approval withdrawn). Removing a supplier is a refusal and a
--     judgement call, and every approval in this company is the CEO's.
--   * the HOLD task — "send no invitation, follow-up or onboarding step to this lead until the
--     decision is made" — goes to the sales_engineer. A sanctions match is a supplier VERIFICATION
--     matter and the supplier-facing outreach it pauses is that seat's work.
-- dept_key goes from 'legal' / 'supply' to NULL on both: there are no departments, and 19 of the 20
-- org_tasks rows alive today already carry dept_key null.
--
-- SWEPT FOR THE SAME CLASS, because one instance is never alone. Every function and procedure in the
-- public schema (live prosrc), every trigger definition, and every edge function under
-- supabase/functions were read for string literals written into a column that names a seat — every
-- column with a foreign key to org_agents, plus assigned_agent, owner_seat, owner_role, from_seat,
