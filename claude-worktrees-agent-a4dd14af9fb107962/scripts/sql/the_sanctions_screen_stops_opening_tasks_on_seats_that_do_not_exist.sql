-- The ACL, written down rather than assumed. CREATE OR REPLACE preserves the existing ACL, so
-- these three lines change nothing today (all three are postgres + service_role only). They are
-- here because a later rewrite that DROPs and CREATEs would grant EXECUTE to PUBLIC by default.
revoke execute on function public.fn_supplier_sanctions_screen(bigint[], text) from public, anon, authenticated;
revoke execute on function public.fn_supplier_screening_decide(bigint, text, text) from public, anon, authenticated;
revoke execute on function public.fn_company_self_knowledge_sync() from public, anon, authenticated;

-- ---------------------------------------------------------------------------------------------
-- THE PROBE: DRIVE THE SCREEN TO AN ACTUAL HIT, BECAUSE A SCREEN THAT FINDS NOTHING PROVES NOTHING
--
-- That is the whole defect. fn_supplier_sanctions_screen has run and reported ok while carrying two
-- assignees that its own foreign key refuses, because it has never matched anybody: production holds
-- 0 screening_run, 0 screening_entry and 0 supplier_screening_hit rows. So this probe SEEDS a hit —
-- one ZZ DEMO supplier and one fixture list entry whose names are identical, which is an exact match
-- on the legal-name field — and makes the INSERT into org_tasks actually run.
--
-- This file also defines routines, so the probe must NOT abort the transaction (that would take the
-- CREATE OR REPLACEs with it, per the estate's apply discipline). It cleans up after itself instead:
-- every row it created is deleted by the id it captured, and the table counts are compared with the
-- counts taken before it started. A single row left behind fails the apply.
--
-- Nothing here can reach a real person: the fixture carries the ZZ DEMO — / @example.invalid
-- convention, and the screen is called WITH a rehearsal tag, which restricts the supplier side of the
-- match to 'ZZ DEMO — %' leads and skips the retention delete. No real lead is read, matched or
-- touched, and no notification is written.
-- ---------------------------------------------------------------------------------------------
do $probe$
declare
  v_name     constant text := 'ZZ DEMO — Sanctioned Trading LLC (seat probe)';
  v_tag      constant text := 'qd_probe:sanctions_seats';
  v_lead bigint; v_run bigint; v_entry bigint; v_res jsonb; v_hit bigint; v_dec jsonb;
  v_task bigint; v_hold bigint; v_ag_task text; v_ag_hold text; v_st_task text; v_st_hold text;
  b jsonb; a jsonb; k text; v_drift text := ''; v_msg text;
  v_ar_max bigint;
begin
  -- leads carries fifteen triggers; a cold one of them timed the probe out once at the default.
  -- Local to this transaction, so nothing outside the apply sees it.
  perform set_config('statement_timeout', '120s', true);

  select jsonb_build_object(
           'leads',                  (select count(*) from public.leads),
           'org_tasks',              (select count(*) from public.org_tasks),
           'supplier_screening_hit', (select count(*) from public.supplier_screening_hit),
           'screening_run',          (select count(*) from public.screening_run),
           'screening_entry',        (select count(*) from public.screening_entry),
           'agent_runs',             (select count(*) from public.agent_runs),
           'undo_log',               (select count(*) from public.undo_log),
           'notifications',          (select count(*) from public.notifications),
           'decision_trace',         (select count(*) from public.decision_trace),
           'review_chain',           (select count(*) from public.review_chain),
           'institutional_memory',   (select count(*) from public.institutional_memory))
    into b;
  select coalesce(max(id), 0) into v_ar_max from public.agent_runs;

  -- the fixture: one list entry and one registered supplier carrying the same name
  insert into public.screening_run (source, source_url, fetched_at, sha256, entries, status, run_tag)
  values ('un_consolidated', 'probe://sanctions-seat-fix', now(), 'probe', 1, 'ok', v_tag)
  returning id into v_run;

  insert into public.screening_entry (run_id, source, entry_type, reference, name, name_norm, tokens)
  values (v_run, 'un_consolidated', 'entity', 'PROBE-SEATS-1', v_name,
          public.fn_screening_normalise(v_name), public.fn_screening_tokens(v_name))
  returning id into v_entry;

  -- lifecycle_stage only: approval_status 'approved' is refused by the mandatory-six gate for a
  -- supplier with no licence, and 'registered' is already one half of the screen's own selector.
  insert into public.leads (company_name, email, lifecycle_stage)
  values (v_name, 'seat.probe@example.invalid', 'registered')
  returning id into v_lead;

  -- THE HIT
  v_res := public.fn_supplier_sanctions_screen(array[v_run], v_tag);
  if coalesce((v_res ->> 'hits_new')::int, 0) < 1 or coalesce((v_res ->> 'leads_hit')::int, 0) < 1 then
    raise exception 'PROBE FAILED: the screen matched nothing, so the task INSERT never ran: %', v_res;
  end if;

  select id, assigned_agent into v_task, v_ag_task from public.org_tasks
   where title = 'Sanctions screening hit: ' || v_name || ' — lead #' || v_lead;
  select id, assigned_agent into v_hold, v_ag_hold from public.org_tasks
   where title = 'Hold outreach and onboarding: ' || v_name || ' — lead #' || v_lead || ' (sanctions screening)';
  if v_task is null or v_hold is null then
    raise exception 'PROBE FAILED: the hit did not open both tasks (decision task %, hold %)', v_task, v_hold;
  end if;
  if v_ag_task <> 'ceo' or v_ag_hold <> 'sales_engineer' then
    raise exception 'PROBE FAILED: the tasks name % and %, not ceo and sales_engineer', v_ag_task, v_ag_hold;
  end if;
  if not exists (select 1 from public.org_agents where agent_key = v_ag_task)
     or not exists (select 1 from public.org_agents where agent_key = v_ag_hold) then
    raise exception 'PROBE FAILED: an assignee is not a live seat (% / %)', v_ag_task, v_ag_hold;
  end if;

  -- THE CLOSE PATH, because the alter table above exists for it. A task carrying dept_key null is
  -- closed through fn_org_task_close_as_fact -> fn_task_review -> fn_review_submit, which writes a
  -- review_chain row carrying that null; before the alter it raised 23502 and the decision could not
  -- be recorded at all. 'false_positive' is the cheap half of the decision: it closes both tasks
  -- without touching the lead's status, which is what this probe needs to prove.
  select id into v_hit from public.supplier_screening_hit where lead_id = v_lead order by id limit 1;
  v_dec := public.fn_supplier_screening_decide(v_hit, 'false_positive');
  if not coalesce((v_dec ->> 'ok')::boolean, false) then
    raise exception 'PROBE FAILED: the decision did not run under its default actor: %', v_dec;
  end if;
  select status into v_st_task from public.org_tasks where id = v_task;
  select status into v_st_hold from public.org_tasks where id = v_hold;
  if v_st_task <> 'done' or v_st_hold <> 'done' then
    raise exception 'PROBE FAILED: the decision left the tasks at % / %, not done', v_st_task, v_st_hold;
  end if;

  -- CLEAN UP AFTER ITSELF, by the ids it captured and nothing else
  delete from public.supplier_screening_hit where lead_id = v_lead;
  delete from public.review_chain        where subject_type = 'org_task' and subject_id in (v_task::text, v_hold::text);
  delete from public.decision_trace      where entity_type = 'org_task' and entity_id in (v_task::text, v_hold::text);
  delete from public.institutional_memory where subject_type = 'org_task' and subject_id in (v_task::text, v_hold::text);
  delete from public.org_tasks     where id in (v_task, v_hold);
  delete from public.undo_log      where table_name = 'org_tasks' and row_id::text in (v_task::text, v_hold::text);
  delete from public.screening_entry where run_id = v_run;
  delete from public.screening_run   where id = v_run;
  delete from public.leads           where id = v_lead;
  -- agent_runs: id-scoped AND content-scoped. A watermark alone would delete whatever another
  -- session committed while this transaction was open; the screen tags its own note with the
  -- rehearsal tag and the close names the task it closed, so both are identified, not guessed.
  delete from public.agent_runs
   where id > v_ar_max
     and (note like '%[rehearsal ' || v_tag || ']%'
       or note like 'org_task ' || v_task || ' closed%'
       or note like 'org_task ' || v_hold || ' closed%');

  select jsonb_build_object(
           'leads',                  (select count(*) from public.leads),
           'org_tasks',              (select count(*) from public.org_tasks),
           'supplier_screening_hit', (select count(*) from public.supplier_screening_hit),
           'screening_run',          (select count(*) from public.screening_run),
           'screening_entry',        (select count(*) from public.screening_entry),
           'agent_runs',             (select count(*) from public.agent_runs),
           'undo_log',               (select count(*) from public.undo_log),
           'notifications',          (select count(*) from public.notifications),
           'decision_trace',         (select count(*) from public.decision_trace),
           'review_chain',           (select count(*) from public.review_chain),
           'institutional_memory',   (select count(*) from public.institutional_memory))
    into a;
  for k in select jsonb_object_keys(b) loop
    if (b ->> k) <> (a ->> k) then
      v_drift := v_drift || k || ' ' || (b ->> k) || '->' || (a ->> k) || '; ';
    end if;
  end loop;

  v_msg := 'sanctions seat probe: lead #' || v_lead || ' matched ' || (v_res ->> 'hits_new')
        || ' new hit(s); the decision task went to ' || v_ag_task || ' and the outreach hold to ' || v_ag_hold
        || ' — both are rows in org_agents, so the foreign key accepted them. Left behind: '
        || case when v_drift = '' then '(nothing)' else v_drift end;
  if v_drift <> '' then
    raise exception 'PROBE FAILED: the probe left rows behind: %', v_drift;
  end if;
  raise notice '%', v_msg;
end $probe$;
