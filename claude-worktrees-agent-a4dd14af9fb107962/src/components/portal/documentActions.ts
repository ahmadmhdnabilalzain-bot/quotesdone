/**
 * A Supabase signed URL opens inline; the same URL with `download=<name>` answers with
 * Content-Disposition: attachment, so the browser saves it. The `download` attribute on an anchor
 * is ignored cross-origin, which is why this is done in the URL and not on the link.
 */
export function downloadUrl(url: string | null | undefined, name?: string | null): string | null {
  if (!url) return null;
  try {
    const u = new URL(url);
    if (!u.searchParams.has('download')) u.searchParams.set('download', String(name || '').trim() || '');
    return u.toString();
  } catch { return url; }
}
