-- AUDIT 4.4 — the 3 Aug fix to agent_knowledge#279 was written into a row that a trigger
-- regenerates WHOLESALE, so it was never actually closed.
--
-- 20260803171625 appended a "START DATE" paragraph to agent_knowledge#279. But #279 is produced
-- by fn_company_facts_sync(), which does `update agent_knowledge set content = txt` — it replaces
-- the whole column. fn_company_facts_sync() is fired by trg_pricing_config_facts on ANY update to
-- public.pricing_config. So the correction survives only until the next time somebody edits the
-- fee, the currency, the free count or the start date — i.e. it is erased at precisely the moment
-- the pricing corpus most needs to be right, and erased silently, because the trigger reports
-- nothing. The generator never knew about supplier_charging_starts at all.
--
-- Fix the GENERATOR, not the row. The start date and the permanence of the founding exemption are
-- facts in pricing_config; the sentence must be derived from them like every other figure in it.

create or replace function public.fn_company_facts_sync()
returns void
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $function$
declare c record; pct text; capnote text; txt text; regline text;
begin
  select * into c from pricing_config where id=1; if c is null then return; end if;

  pct := trim(to_char(coalesce(c.standard_reveal_rate,0)*100,'FM990.##'))||'%';
  capnote := case when coalesce(c.standard_reveal_cap,0) >= 1000000
                  then 'no cap'
                  else 'capped at '||coalesce(c.reveal_currency,'AED')||' '||trim(to_char(c.standard_reveal_cap,'FM999999990')) end;

  -- The registration sentence is DERIVED, including the date. A generator that silently omits the
  -- start date produces a row that reads as "charged today" to every agent that retrieves it.
  if c.supplier_charging_starts is null then
    regline := 'Supplier registration: the annual subscription START DATE IS NOT SET in pricing_config — '
            || 'do NOT state when the fee begins; say the founder must confirm it. ';
  else
    regline := 'Supplier registration is FREE for EVERY supplier until '
            || to_char(c.supplier_charging_starts - 1, 'FMDD FMMonth YYYY') || '. '
            || 'From ' || to_char(c.supplier_charging_starts, 'FMDD FMMonth YYYY') || ' a '
            || coalesce(c.supplier_reg_period,'yearly') || ' subscription of '
            || coalesce(c.supplier_reg_currency,'AED') || ' '
            || trim(to_char(c.supplier_reg_fee,'FM999,999,990.##')) || ' applies, and it is NOT charged '
            || 'before that date. The first ' || c.supplier_free_count || ' businesses to register are '
            || 'exempt PERMANENTLY and never pay it — that exemption does not expire. ';
  end if;

  txt := 'PRICING & FEES — LIVE, AUTO-SYNCED FROM pricing_config (authoritative; OVERRIDES any pricing figure stated elsewhere). '
    ||'Customer REVEAL FEE: '||pct||' of the accepted quotation value ('||capnote||'), paid by the customer to unlock their chosen supplier. '
    ||'Suppliers pay NO commission on won jobs. '
    ||regline
    ||'Non-response window: '||c.refund_window_working_days||' working days — if a revealed supplier does not respond in that window and cannot be reached, the customer reveal fee is refunded and the supplier is charged a non-response fee equal to that reveal fee and blocked from matching until paid. '
    ||'There is NO 2% fee and NO supplier commission — never quote those. (Auto-updated '||to_char(now(),'YYYY-MM-DD HH24:MI')||' UTC.)';

  update agent_knowledge set content=txt, priority=100, updated_at=now()
    where agent_key='_global' and topic='Pricing & fees (LIVE — auto-synced)';
  if not found then
    insert into agent_knowledge(agent_key,topic,content,priority,updated_at)
      values ('_global','Pricing & fees (LIVE — auto-synced)',txt,100,now());
  end if;
end $function$;

-- Regenerate the row from the corrected generator. This deliberately DISCARDS the hand-appended
-- paragraph from 20260803171625: the same facts now come out of the generator, so there is nothing
-- left for a future pricing_config edit to erase.
select public.fn_company_facts_sync();

-- Two hand-authored corpus rows carry the same stale claim. They are not generated by anything
-- (checked: no function references 'canon:money' or 'Company primer'), so they are corrected here.
update public.agent_knowledge
   set content = replace(content,
         'no registration fee at launch (first 1,000 suppliers free, then AED 1,000/year applied later)',
         'no registration fee until 31 July 2027 (AED 1,000/year begins 1 August 2027; the first 1,000 registered suppliers are exempt permanently and never pay it)'),
       updated_at = now()
 where id = 1 and content like '%applied later%';

update public.agent_knowledge
   set content = replace(content,
         'Supplier registration FREE for first 1,000 suppliers then AED 1,000/year (dormant - all free-tier).',
         'Supplier registration FREE for EVERY supplier until 31 July 2027; AED 1,000/year begins 1 August 2027; the first 1,000 registered suppliers are exempt PERMANENTLY. Dormant today - all free-tier.'),
       updated_at = now()
 where id = 3520 and content like '%dormant - all free-tier%';

-- A watch, not a constraint: a corpus table is the wrong place for a CHECK, but a row that names
-- the subscription and omits its start year is exactly the defect 4.4 is about, and it should be
-- visible the moment it reappears.
create or replace view public.v_pricing_knowledge_drift as
  select id, agent_key, topic, updated_at,
         left(content, 200) as starts_with
    from public.agent_knowledge
   where (content ilike '%registration%' or content ilike '%subscription%')
     and (content ilike '%AED 1,000/year%' or content ilike '%AED 1000/year%'
          or content ilike '%1,000 suppliers free%' or content ilike '%first 1000 suppliers FREE%')
     and content not like '%2027%';

comment on view public.v_pricing_knowledge_drift is
  'AUDIT 4.4: agent_knowledge rows that state the supplier subscription without its 2027 start date. Must stay empty.';

do $mig$
declare v_txt text; n int;
begin
  select content into v_txt from agent_knowledge
   where agent_key='_global' and topic='Pricing & fees (LIVE — auto-synced)';
  if v_txt is null then raise exception '4.4: pricing row missing after sync'; end if;
  if v_txt not like '%2027%' then raise exception '4.4: regenerated pricing row still has no start date: %', left(v_txt,300); end if;
  if v_txt not like '%PERMANENTLY%' then raise exception '4.4: regenerated pricing row does not state the exemption is permanent'; end if;

  select count(*) into n from public.v_pricing_knowledge_drift;
  if n > 0 then raise exception '4.4: % agent_knowledge row(s) still state the subscription with no start date', n; end if;

  raise notice '4.4: generator now derives the start date; drift view empty';
end $mig$;
