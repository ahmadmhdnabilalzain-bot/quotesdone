-- OS-level event subscription: an OS subscribes, and the dispatcher fans out to its owner.
insert into event_subscription (agent_key, event_type, reason, active)
select o.owner_agent, i.event_type,
       'OS interface: '||o.name||' consumes '||i.kind, true
from os_interface i join operating_system o on o.os_key = i.os_key
where i.direction='input' and i.event_type is not null and o.owner_agent is not null
  and not exists (select 1 from event_subscription s where s.agent_key=o.owner_agent and s.event_type=i.event_type);