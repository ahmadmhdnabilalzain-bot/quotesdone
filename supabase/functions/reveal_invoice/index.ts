async function secret(k: string) { const { data } = await admin.from('app_secrets').select('value').eq('key', k).maybeSingle(); return (data?.value as string) || ''; }
async function signedDoc(bucket: string, path: string, ttl = 3600) { try { const { data } = await admin.storage.from(bucket || 'agent-docs').createSignedUrl(path, ttl); return data?.signedUrl || null; } catch { return null; } }

// The accountant's invoice door for the customer. Since 21 Sep 2026 (founder, instructions 568 and
// 569: "not a single pdf should be generated by our team unless its as per our template") it serves
// ONLY QuotesDone template documents: the invoice (doc 'invoice', the default) and the receipt
// (doc 'receipt'), each in English or Arabic, rendered by pdf_native from reveal_fee_documents.ts.
// The link is a signed storage URL, which a browser shows in the tab it opened; the Stripe file it
